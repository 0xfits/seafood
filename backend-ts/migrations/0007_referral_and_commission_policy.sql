--   ⑥ 「Σ佣金 == 手续费」DB 侧后置断言（裁定 #14 / CR80）：**只读** `CONSTRAINT TRIGGER`
--      on `ledger_entry`（AFTER INSERT · DEFERRABLE INITIALLY DEFERRED）⇒ 失败抛**既有对账码**
--      `LEDGER_RECONCILE_MISMATCH`（关闭集第 33 码），**禁裸抛 23514、禁新增码**。
--   ⑦ 迁移自检（CR55）：把 P2 的准入前提（`-2` 白名单 + kind 关闭集）钉在 0007 里。
--
-- 本迁移**不**做什么（硬边界）
--   · **不改 `0001`–`0006` 的任何字节**（checksum 纪律：改一字节 ⇒ migrate.ts 整链 ABORT/exit 3）
--   · **不改 `ledger_post_event` 函数体**（裁定 #14 明令禁止）⇒ 只**新增** `ledger_entry` 上的
