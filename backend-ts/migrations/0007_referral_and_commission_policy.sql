-- ---------------------------------------------------------------------------
-- §B.2 政策写入守卫（CR83）—— `Σ` 与「前缀全零」**无法用 CHECK 表达**（PG 的 CHECK 禁子查询 /
--      集合函数）⇒ 唯一落点 = BEFORE INSERT OR UPDATE 触发器。失败一律 `23514` ⇒ 既有分类器
--      （0005 `ledger_error_for_sqlstate`）对「其余 23514」归 `input` ⇒ `400`
--      `LEDGER_AMOUNT_INVALID`（+ 前缀化 reason）。**不得**改 0005 的分桶、**不得**新增错误码。
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION commission_policy_weights_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE v_sum integer;
BEGIN
  IF array_length(NEW.weights_bp, 1) IS DISTINCT FROM NEW.levels THEN
    RAISE EXCEPTION 'commission_policy_weights_guard: weights_bp length (%) <> levels (%)',
          array_length(NEW.weights_bp, 1), NEW.levels
      USING ERRCODE = '23514';
  END IF;
  v_sum := COALESCE((SELECT sum(w) FROM unnest(NEW.weights_bp) AS w), 0);
  IF (SELECT count(*) FROM unnest(NEW.weights_bp) AS w WHERE w IS NULL OR w < 0) > 0 THEN
    RAISE EXCEPTION 'commission_policy_weights_guard: negative/null weight in %', NEW.weights_bp
      USING ERRCODE = '23514';
  END IF;
  IF v_sum > 10000 THEN
    RAISE EXCEPTION 'commission_policy_weights_guard: sum(weights_bp) = % > 10000', v_sum
      USING ERRCODE = '23514';
  END IF;
  -- 裁定 #16：退化分母 W = 0 在**政策写入时**就拒（运行时因此不可达）
  IF v_sum = 0 THEN
    RAISE EXCEPTION 'commission_policy_weights_guard: sum(weights_bp) = 0 (degenerate denominator W = 0)'
      USING ERRCODE = '23514';
  END IF;
  -- 裁定 #16 / master-plan §5.21 #2：可静态判定式 = `weights_bp[1] > 0`（M = min(levels, 链深) ∈ [1,levels]）
  IF NEW.weights_bp[1] IS NULL OR NEW.weights_bp[1] = 0 THEN
    RAISE EXCEPTION 'commission_policy_weights_guard: weights_bp[1] = % (prefix-all-zero => W = 0 when M = 1)',
          NEW.weights_bp[1]
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_commission_policy_weights_guard ON commission_policy;
CREATE TRIGGER trg_commission_policy_weights_guard
BEFORE INSERT OR UPDATE ON commission_policy
FOR EACH ROW EXECUTE FUNCTION commission_policy_weights_guard();

