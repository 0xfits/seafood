--   · 不建 `commission_payout` 表（裁定 #4）；不新增错误码 / 不新增 kind（CR5 / CR75）
--   · 不改 `ledger_entry` 表结构、不写任何业务表（断言触发器**只读**）
--   · ⚠️ `-1` 白名单接纳 `job_fee` **不在本文件**（属既有对象行为改变）⇒ 落在 `0008`
--
-- 幂等：每条 DDL 自带存在性守卫（`IF NOT EXISTS` / `to_regclass` / `DROP TRIGGER IF EXISTS`
