-- ============================================================================
-- §D 结算分录派生（commission.spec §5.3 顺序铁律 + §6.2 最大余数法；DL86 分支）
-- ============================================================================
-- 纯派生函数（STABLE，只读 commission_policy / referral）：
--   fee = (gross × fee_rate_bp + 5000) / 10000      -- CR38：全项目唯一取整点（半进位）
--   net = gross − fee                               -- CR39 / D14：减法求净额，net+fee == gross 恒等
--   M   = min(policy.levels, chain_depth)           -- CR46
--   W   = Σ_{L<=M} w_L                              -- CR47：重归一化的唯一分母（不是 10000）
--   q_L = (P × w_L) / W ; r_L = (P × w_L) mod W ; D = P − Σq
--   order = (r_L DESC, L DESC) 全序 ⇒ 前 D 名 +1 ⇒ Σx_L == P 逐分不差
--   x_L = 0 的层不建分录（CR48）；fee = 0 ⇒ 只有 job_payout 两条（CR51）；
--   无邀请人（M=0）⇒ fee 增方 = uid −1（平台收入，DL86），不得写 −2。
CREATE OR REPLACE FUNCTION public.job_settle_plan(
  p_job_id bigint, p_employer bigint, p_worker bigint, p_cid bigint, p_gross bigint
) RETURNS jsonb
LANGUAGE plpgsql STABLE AS $$
DECLARE
  v_bp      integer;
  v_levels  smallint;
  v_weights smallint[];
  v_cur     bigint;
  v_anc     bigint;
  v_chain   bigint[] := '{}';
  v_fee     bigint;
  v_net     bigint;
  v_pool    bigint;
  v_credit  bigint;
  v_M       integer;
  v_w       bigint[] := '{}';
  v_wsum       bigint := 0;
  v_q       bigint[] := '{}';
  v_r       bigint[] := '{}';
  v_x       bigint[] := '{}';
  v_order   integer[];
  v_sumq    bigint := 0;
  v_sumx    bigint := 0;
  v_D       bigint;
  v_layers  jsonb := '[]'::jsonb;
  v_entries jsonb := '[]'::jsonb;
  v_memo    text;
  v_N       integer := 0;
  i         integer;
BEGIN
  IF p_gross IS NULL OR p_gross <= 0 THEN
    PERFORM public.ledger_raise('LEDGER_AMOUNT_NOT_POSITIVE',
      jsonb_build_object('field', 'reward', 'value', COALESCE(p_gross::text, 'null')));
  END IF;
  IF p_worker IS NULL THEN
    -- 未选定打工人 = 无结算对象（§11.2「无权/状态类」借码；reason 小写下划线形态）
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job.worker_uid', 'reason', 'not_job_worker', 'job_id', p_job_id::text));
  END IF;

  -- 政策取「now() 生效的最新一版」（CR23：policy(now())；commission_policy 是 INSERT-only）
  SELECT cp.fee_rate_bp, cp.levels, cp.weights_bp
    INTO v_bp, v_levels, v_weights
    FROM public.commission_policy cp
   WHERE cp.effective_from <= now()
   ORDER BY cp.effective_from DESC
   LIMIT 1;
  IF NOT FOUND THEN
    PERFORM public.ledger_raise('LEDGER_FEE_RATE_INVALID',
      jsonb_build_object('reason', 'policy_weights_all_zero', 'job_id', p_job_id::text,
                         'note', 'no commission_policy row effective at now()'));
  END IF;

  v_fee  := (p_gross * v_bp + 5000) / 10000;   -- CR38
  v_net  := p_gross - v_fee;                    -- CR39
  v_pool := v_fee;

  -- 链：从 worker 向上遍历 ≤ levels 层（DL51 归属：上级受益人 = 直接邀请人起逐层上溯）
  v_cur := p_worker;
  FOR i IN 1..LEAST(v_levels::integer, 10) LOOP
    SELECT r.parent_uid INTO v_anc FROM public.referral r WHERE r.child_uid = v_cur;
    EXIT WHEN NOT FOUND;
    v_chain := v_chain || v_anc;
    v_cur := v_anc;
  END LOOP;
  v_M := COALESCE(array_length(v_chain, 1), 0);

  IF v_M = 0 THEN
    v_credit := -1;                              -- DL86：无可付祖先 ⇒ 平台收入
  ELSE
    v_credit := -2;                              -- DL86：有可付祖先 ⇒ 佣金池
  END IF;

  -- 最大余数法（仅 fee > 0 且 M > 0 时需要分配）
  IF v_fee > 0 AND v_M > 0 THEN
    FOR i IN 1..v_M LOOP
      v_w := v_w || v_weights[i]::bigint;
      v_wsum := v_wsum + v_weights[i]::bigint;
    END LOOP;
    IF v_wsum <= 0 THEN
      -- §7.3：W = 0 在政策写入时已被 0007 守卫拒（裁定 #16）⇒ 运行时不可达；兜底按 defect 类
      PERFORM public.ledger_raise('LEDGER_FEE_RATE_INVALID',
        jsonb_build_object('reason', 'policy_weights_all_zero', 'levels', v_M, 'job_id', p_job_id::text,
                           'note', 'runtime W=0 branch unreachable under 0007 write-time guard'));
    END IF;
    FOR i IN 1..v_M LOOP
      v_q := v_q || ((v_pool * v_w[i]) / v_wsum);
      v_r := v_r || ((v_pool * v_w[i]) % v_wsum);
      v_sumq := v_sumq + ((v_pool * v_w[i]) / v_wsum);
    END LOOP;
    v_D := v_pool - v_sumq;
    IF v_D < 0 OR v_D > v_M THEN
      PERFORM public.ledger_raise('LEDGER_ACCOUNT_GUARD_VIOLATION',
        jsonb_build_object('reason', 'COMMISSION_SPLIT_SUM_MISMATCH', 'D', v_D::text, 'M', v_M::text));
    END IF;
    v_x := v_q;
    v_order := ARRAY(
      SELECT g.ord FROM generate_series(1, v_M) AS g(ord)
       ORDER BY v_r[g.ord] DESC, g.ord DESC);    -- CR42：余数相同 ⇒ 更深层优先
    FOR i IN 1..v_D::integer LOOP
      v_x[v_order[i]] := v_x[v_order[i]] + 1;
    END LOOP;
    FOR i IN 1..v_M LOOP
      v_sumx := v_sumx + v_x[i];
    END LOOP;
    IF v_sumx <> v_pool THEN
      PERFORM public.ledger_raise('LEDGER_ACCOUNT_GUARD_VIOLATION',
        jsonb_build_object('reason', 'COMMISSION_SPLIT_SUM_MISMATCH',
                           'pool', v_pool::text, 'sum_x', v_sumx::text, 'M', v_M::text));
    END IF;
  END IF;

  -- ---------------------------------------------------------------- 分录（§5.3 顺序铁律）
  v_memo := '招工验收结算 job=' || p_job_id::text;
  v_entries := jsonb_build_array(
    jsonb_build_object('uid', p_employer::text, 'cid', p_cid::text, 'delta', '0',
                       'frozen_delta', (-v_net)::text, 'kind', 'job_payout',
                       'memo', v_memo || '（雇主托管出账）'),
    jsonb_build_object('uid', p_worker::text, 'cid', p_cid::text, 'delta', v_net::text,
                       'frozen_delta', '0', 'kind', 'job_payout',
                       'memo', v_memo || '（打工人到手）'));

  IF v_fee > 0 THEN
    v_entries := v_entries || jsonb_build_array(
      jsonb_build_object('uid', p_employer::text, 'cid', p_cid::text, 'delta', '0',
                         'frozen_delta', (-v_fee)::text, 'kind', 'job_fee',
                         'memo', v_memo || '（手续费）'),
      jsonb_build_object('uid', v_credit::text, 'cid', p_cid::text, 'delta', v_fee::text,
                         'frozen_delta', '0', 'kind', 'job_fee',
                         'memo', v_memo || '（手续费入账）'));
    IF v_M > 0 THEN
      FOR i IN 1..v_M LOOP
        IF v_x[i] > 0 THEN
          v_N := v_N + 1;
          v_layers := v_layers || jsonb_build_array(jsonb_build_object(
            'level', i, 'beneficiary_uid', v_chain[i]::text, 'weight_bp', v_w[i]::text,
            'q', v_q[i]::text, 'r', v_r[i]::text, 'x', v_x[i]::text));
          v_entries := v_entries || jsonb_build_array(
            jsonb_build_object('uid', '-2', 'cid', p_cid::text, 'delta', (-v_x[i])::text,
                               'frozen_delta', '0', 'kind', 'commission',
                               'memo', v_memo || '（佣金 L' || i || '）'),
            jsonb_build_object('uid', v_chain[i]::text, 'cid', p_cid::text, 'delta', v_x[i]::text,
                               'frozen_delta', '0', 'kind', 'commission',
                               'memo', v_memo || '（佣金 L' || i || '）'));
        END IF;
      END LOOP;
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'job_id', p_job_id::text, 'employer_uid', p_employer::text, 'worker_uid', p_worker::text,
    'cid', p_cid::text, 'gross', p_gross::text, 'fee', v_fee::text, 'net', v_net::text,
    'pool', v_pool::text, 'fee_rate_bp', v_bp, 'levels', v_levels, 'M', v_M, 'N', v_N,
    'W', v_wsum::text, 'weights_bp', to_jsonb(v_w), 'fee_credit_uid', v_credit::text,
    'zero_amount', (v_fee = 0), 'no_referrer', (v_M = 0),
    'layers', v_layers, 'entries', v_entries);
END $$;

COMMENT ON FUNCTION public.job_settle_plan(bigint, bigint, bigint, bigint, bigint) IS
  '招工结算分录派生（commission.spec §5.3 顺序铁律 + §6.2 最大余数法；DL86 的 -2/-1 分支）。只读、不写库、不锁账户；金额一律十进制字符串（R70）。';


-- ============================================================================
-- §E 业务编排函数 `public.job_post_event(payload jsonb)`（DL20 提案 A / DL141–DL144）
-- ============================================================================
-- 入参契约（amounts 一律十进制字符串，R70）
--   { "op": "publish" | "refund" | "settle",
--     "request_fingerprint": "<hex>"|null,          -- 路由层强制传（DL96）；本函数透传
--     "memo": "…"?,                                 -- 可选
--     "create_key": "cli:<uuid-v4>",                -- op=publish 必填（创建类键，DL94）
--     "employer_uid": "900001", "cid": "1", "reward": "1000",
--     "title": "…"?, "description": "…"?,
--     "job_id": "123",                              -- op=refund|settle 必填
--     "to_status": "cancelled"|"rejected" }         -- op=refund 必填（cancel / reject）
-- 幂等键**由本函数确定性派生**（DL95：键只能由不可变业务标识派生；调用方不得自造）：
--   publish → `biz:job:escrow:<job_id>`（创建本身用 create_key = `cli:<uuid>`，DL58）
--   refund  → `biz:job:refund:<job_id>`
--   settle  → `biz:job:settle:<job_id>`（逐字对齐 CR57）
-- 出参：{ok, idempotent_replay, op, job_id, status, escrow_txid, settle_txid,
--        ledger_event_keys, txid, created, entries, accounts, extra}
CREATE OR REPLACE FUNCTION public.job_post_event(payload jsonb) RETURNS jsonb
LANGUAGE plpgsql AS $$
DECLARE
  v_op         text;
  v_fp         text;
  v_memo       text;
  v_create_key text;
  v_employer   bigint;
  v_cid        bigint;
  v_reward     bigint;
  v_title      text;
  v_desc       text;
  v_to         text;
  v_job_id     bigint;
  v_job        public.job;
  v_key        text;
  v_entries    jsonb;
  v_plan       jsonb;
  v_replay     boolean := false;
  v_created    boolean := false;
  v_ledger     jsonb;
  v_txid       text;
  v_seen       integer;
  v_bad        text;
  v_cur        record;
BEGIN
  -- ---------------------------------------------------------------- 信封校验
  IF payload IS NULL OR jsonb_typeof(payload) <> 'object' THEN
    PERFORM public.ledger_raise('LEDGER_AMOUNT_INVALID',
      jsonb_build_object('field', 'payload', 'reason', 'BAD_TYPE'));
  END IF;
  v_op := payload->>'op';
  IF v_op IS NULL OR v_op NOT IN ('publish', 'refund', 'settle') THEN
    PERFORM public.ledger_raise('LEDGER_AMOUNT_INVALID',
      jsonb_build_object('field', 'op', 'value', COALESCE(v_op, 'null'), 'reason', 'UNKNOWN_JOB_OP'));
  END IF;
  -- R53 / §19.6：指纹可为 NULL（未传 = 同键即重放）；只作用于事件第 1 条分录
  IF payload ? 'request_fingerprint' AND jsonb_typeof(payload->'request_fingerprint') = 'string' THEN
    v_fp := NULLIF(payload->>'request_fingerprint', '');
  ELSE
    v_fp := NULL;
  END IF;
  v_memo := COALESCE(NULLIF(payload->>'memo', ''), 'job ' || v_op);

  IF v_op = 'publish' THEN
    -- ============================================================ op = publish
    -- ① 创建幂等键闸（DL93 的字符集闸，逐项同序：TOO_LONG → PREFIX_REQUIRED →
    --    RESERVED_SEPARATOR → CONTROL_CHARACTER）
    v_create_key := btrim(COALESCE(payload->>'create_key', ''));
    IF v_create_key = '' OR jsonb_typeof(payload->'create_key') <> 'string' THEN
      PERFORM public.ledger_raise('LEDGER_IDEMPOTENCY_KEY_REQUIRED',
        jsonb_build_object('field', 'create_key'));
    END IF;
    IF length(v_create_key) > 256 THEN
      PERFORM public.ledger_raise('LEDGER_IDEMPOTENCY_KEY_INVALID',
        jsonb_build_object('reason', 'TOO_LONG', 'field', 'create_key'));
    END IF;
    IF v_create_key !~ '^(biz|cm|cli|ops):' THEN
      PERFORM public.ledger_raise('LEDGER_IDEMPOTENCY_KEY_INVALID',
        jsonb_build_object('reason', 'PREFIX_REQUIRED', 'provided', left(v_create_key, 8), 'field', 'create_key'));
    END IF;
    IF position('#' in v_create_key) > 0 THEN
      PERFORM public.ledger_raise('LEDGER_IDEMPOTENCY_KEY_INVALID',
        jsonb_build_object('reason', 'RESERVED_SEPARATOR', 'field', 'create_key'));
    END IF;
    IF v_create_key ~ '[[:cntrl:]]' THEN
      PERFORM public.ledger_raise('LEDGER_IDEMPOTENCY_KEY_INVALID',
        jsonb_build_object('reason', 'CONTROL_CHARACTER', 'field', 'create_key'));
    END IF;
    -- 入参解析（R100：body 侧 uid 必须 > 0；平台保留区间一律拒）
    v_employer := public.ledger_uid_arg(COALESCE(payload->>'employer_uid', ''), 'employer_uid');
    IF v_employer < 1 THEN
      PERFORM public.ledger_raise('LEDGER_RESERVED_UID',
        jsonb_build_object('uid', v_employer::text, 'field', 'employer_uid',
                           'reason', 'PLATFORM_EMPLOYER_FORBIDDEN'));
    END IF;
    v_cid    := public.ledger_cid_arg(COALESCE(payload->>'cid', ''));
    v_reward := public.ledger_int_amount(COALESCE(payload->>'reward', ''), 'reward');
    IF v_reward <= 0 THEN
      PERFORM public.ledger_raise('LEDGER_AMOUNT_NOT_POSITIVE',
        jsonb_build_object('field', 'reward', 'value', v_reward::text));
    END IF;
    IF v_reward > public.ledger_max_single_amount() THEN
      PERFORM public.ledger_raise('LEDGER_AMOUNT_INVALID',
        jsonb_build_object('field', 'reward', 'reason', 'OVER_MAX_SINGLE_AMOUNT', 'value', left(v_reward::text, 40)));
    END IF;
    v_title := COALESCE(payload->>'title', '');
    v_desc  := COALESCE(payload->>'description', '');
    IF length(v_title) > 200 THEN
      PERFORM public.ledger_raise('LEDGER_AMOUNT_INVALID',
        jsonb_build_object('field', 'title', 'reason', 'TOO_LONG', 'limit', 200));
    END IF;

    -- ② 业务行锁（DL141：业务行先于 currency/account）。create_key 是创建幂等的唯一权威
    SELECT * INTO v_job FROM public.job j WHERE j.create_key = v_create_key FOR UPDATE;
    IF FOUND THEN
      v_replay := true;
      -- 同键异业务内容 ⇒ 409（DL144② 的业务侧对应物；有指纹时账本侧另有一道闸）
      IF v_job.employer_uid <> v_employer OR v_job.cid <> v_cid OR v_job.reward <> v_reward THEN
        PERFORM public.ledger_raise('LEDGER_IDEMPOTENCY_CONFLICT',
          jsonb_build_object('reason', 'CREATE_KEY_REUSED_WITH_DIFFERENT_CONTENT',
                             'field', 'create_key', 'idempotency_key', v_create_key,
                             'job_id', v_job.job_id::text));
      END IF;
    ELSE
      INSERT INTO public.job (employer_uid, cid, reward, title, description, status, create_key)
      VALUES (v_employer, v_cid, v_reward, v_title, v_desc, 'open', v_create_key)
      ON CONFLICT (create_key) DO NOTHING
      RETURNING * INTO v_job;
      IF NOT FOUND THEN
        -- 并发同键：另一事务已建行 ⇒ 重读（持行锁），按重放返回，不重写业务行
        SELECT * INTO v_job FROM public.job j WHERE j.create_key = v_create_key FOR UPDATE;
        IF NOT FOUND THEN
          PERFORM public.ledger_raise('LEDGER_REF_NOT_FOUND',
            jsonb_build_object('field', 'create_key', 'reason', 'job_create_race_lost',
                               'idempotency_key', v_create_key));
        END IF;
        v_replay := true;
      ELSE
        v_created := true;
      END IF;
    END IF;

    v_job_id := v_job.job_id;
    v_key    := 'biz:job:escrow:' || v_job_id::text;

    -- R28：招工酬金计价仅 `listed`（只在**发布托管**路径上校验；退款/结算不受币种状态影响）
    SELECT c.cid, c.status INTO v_cur FROM public.currency c WHERE c.cid = v_job.cid;
    IF NOT FOUND THEN
      PERFORM public.ledger_raise('LEDGER_CURRENCY_NOT_FOUND', jsonb_build_object('cid', v_job.cid::text));
    END IF;
    IF v_cur.status <> 'listed' THEN
      PERFORM public.ledger_raise('LEDGER_CURRENCY_NOT_LISTED',
        jsonb_build_object('cid', v_job.cid::text, 'symbol', NULL, 'reason', 'job_reward_currency_not_listed', 'status', v_cur.status));
    END IF;

    -- ③ 派生分录（§7.1：`job_escrow` ×2，雇主 balance −n / 雇主 frozen +n；DL90 例外）
    v_entries := jsonb_build_array(
      jsonb_build_object('uid', v_job.employer_uid::text, 'cid', v_job.cid::text, 'delta', (-v_job.reward)::text,
                         'frozen_delta', '0', 'kind', 'job_escrow',
                         'memo', '招工发布托管 job=' || v_job_id::text || '（雇主余额出账）'),
      jsonb_build_object('uid', v_job.employer_uid::text, 'cid', v_job.cid::text, 'delta', '0',
                         'frozen_delta', v_job.reward::text, 'kind', 'job_escrow',
                         'memo', '招工发布托管 job=' || v_job_id::text || '（入冻结）'));

  ELSE
    -- ============================================================ op = refund | settle
    v_job_id := public.ledger_int_amount(COALESCE(payload->>'job_id', ''), 'job_id');
    IF v_job_id < 1 THEN
      PERFORM public.ledger_raise('LEDGER_REF_NOT_FOUND',
        jsonb_build_object('field', 'job_id', 'value', v_job_id::text, 'reason', 'job_not_found'));
    END IF;
    IF v_op = 'refund' THEN
      v_to := COALESCE(NULLIF(payload->>'to_status', ''), 'cancelled');
      IF v_to NOT IN ('cancelled', 'rejected') THEN
        PERFORM public.ledger_raise('LEDGER_AMOUNT_INVALID',
          jsonb_build_object('field', 'to_status', 'value', v_to, 'reason', 'not_a_refund_target'));
      END IF;
      v_key := 'biz:job:refund:' || v_job_id::text;
    ELSE
      v_to  := 'settled';
      v_key := 'biz:job:settle:' || v_job_id::text;
    END IF;

    -- ① 业务行锁（DL141 全序第 1 段；单行按主键）
    SELECT * INTO v_job FROM public.job j WHERE j.job_id = v_job_id FOR UPDATE;
    IF NOT FOUND THEN
      PERFORM public.ledger_raise('LEDGER_REF_NOT_FOUND',
        jsonb_build_object('field', 'job_id', 'value', v_job_id::text, 'reason', 'job_not_found'));
    END IF;

    -- ② 重放探测（**只读**，按事件根键走已有索引 idx_ledger_event_root_key）
    --    与 0012 的重放前置闸同法：它只决定「是否还走业务状态机校验」，不取代账本的权威幂等探针。
    SELECT 1 INTO v_seen FROM public.ledger_entry e WHERE e.event_root_key = v_key LIMIT 1;
    v_replay := FOUND;

    -- ③ 状态机闸（DL51/DL52；**仅非重放**：重放时业务行已在终态，不得第二次校验/重写）
    IF NOT v_replay THEN
      IF NOT public.job_status_transition_ok(v_job.status, v_to) THEN
        PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
          jsonb_build_object('field', 'job.status', 'reason', 'JOB_STATE_INVALID',
                             'from', v_job.status, 'to', v_to, 'job_id', v_job_id::text));
      END IF;
    END IF;

    -- ④ 派生分录
    IF v_op = 'refund' THEN
      IF v_job.escrow_txid IS NULL THEN
        -- 未托管 ⇒ 无可退（结构性判据；防「凭空退款」）
        PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
          jsonb_build_object('field', 'job.escrow_txid', 'reason', 'job_escrow_missing',
                             'job_id', v_job_id::text, 'status', v_job.status));
      END IF;
      v_entries := jsonb_build_array(
        jsonb_build_object('uid', v_job.employer_uid::text, 'cid', v_job.cid::text, 'delta', v_job.reward::text,
                           'frozen_delta', '0', 'kind', 'job_escrow_refund',
                           'memo', '招工托管退回 job=' || v_job_id::text || '（出冻结）'),
        jsonb_build_object('uid', v_job.employer_uid::text, 'cid', v_job.cid::text, 'delta', '0',
                           'frozen_delta', (-v_job.reward)::text, 'kind', 'job_escrow_refund',
                           'memo', '招工托管退回 job=' || v_job_id::text || '（回余额）'));
    ELSE
      v_plan    := public.job_settle_plan(v_job.job_id, v_job.employer_uid, v_job.worker_uid, v_job.cid, v_job.reward);
      v_entries := v_plan->'entries';
    END IF;
  END IF;

  -- ---------------------------------------------------------------- DL84 事件级 kind 白名单
  FOR v_cur IN SELECT t.e->>'kind' AS k FROM jsonb_array_elements(v_entries) AS t(e) LOOP
    IF (v_op = 'publish' AND v_cur.k <> 'job_escrow')
       OR (v_op = 'refund' AND v_cur.k <> 'job_escrow_refund')
       OR (v_op = 'settle' AND v_cur.k NOT IN ('job_payout', 'job_fee', 'commission')) THEN
      PERFORM public.ledger_raise('LEDGER_ACCOUNT_GUARD_VIOLATION',
        jsonb_build_object('reason', 'JOB_EVENT_KIND_OUT_OF_WHITELIST', 'op', v_op, 'kind', v_cur.k));
    END IF;
  END LOOP;

  -- ---------------------------------------------------------------- DL141/DL143：调既有账本函数
  -- 锁序：业务行（上方已 `FOR UPDATE`）→ currency（cid 升序）→ account（uid 升序）—— 由
  -- `ledger_post_event` 在其内部完成第二、三段；本函数**绝不**先锁 account（否则 AB-BA 死锁）。
  v_ledger := public.ledger_post_event(jsonb_build_object(
    'op',                  'entries',
    'idempotency_key',     v_key,
    'request_fingerprint', v_fp,
    'memo',                v_memo,
    'ref_type',            'job',
    'ref_id',              v_job_id::text,
    'entries',             v_entries));
  v_txid := v_ledger->>'txid';
  IF (v_ledger->>'idempotent_replay')::boolean THEN
    v_replay := true;
  END IF;

  -- ---------------------------------------------------------------- 回写业务行
  -- DL144①：重放 ⇒ **不重写业务行**、**不追加 `ledger_event_keys` 项**（DL149 判负用例钉住）；
  -- 判据是账本侧的 `idempotent_replay`（+ 只读根键探测），**不是** `UPDATE ... RETURNING` 的行数。
  IF NOT v_replay THEN
    IF v_op = 'publish' THEN
      UPDATE public.job j
         SET escrow_txid = v_txid::bigint,
             ledger_event_keys = j.ledger_event_keys || v_key
       WHERE j.job_id = v_job_id
      RETURNING * INTO v_job;
    ELSIF v_op = 'refund' THEN
      UPDATE public.job j
         SET status = v_to,
             ledger_event_keys = j.ledger_event_keys || v_key
       WHERE j.job_id = v_job_id
      RETURNING * INTO v_job;
    ELSE
      UPDATE public.job j
         SET status = 'settled',
             settle_txid = v_txid::bigint,
             ledger_event_keys = j.ledger_event_keys || v_key
       WHERE j.job_id = v_job_id
      RETURNING * INTO v_job;
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'idempotent_replay', v_replay,
    'op', v_op,
    'job_id', v_job_id::text,
    'created', v_created,
    'status', v_job.status,
    'escrow_txid', CASE WHEN v_job.escrow_txid IS NULL THEN NULL ELSE v_job.escrow_txid::text END,
    'settle_txid', CASE WHEN v_job.settle_txid IS NULL THEN NULL ELSE v_job.settle_txid::text END,
    'ledger_event_keys', to_jsonb(v_job.ledger_event_keys),
    'txid', v_txid,
    'ledger_idempotency_key', v_key,
    'entries', v_ledger->'entries',
    'accounts', v_ledger->'accounts',
    'extra', jsonb_build_object('job_op', v_op, 'fee_credit_uid',
                                CASE WHEN v_plan IS NULL THEN NULL ELSE v_plan->>'fee_credit_uid' END));
END $$;

COMMENT ON FUNCTION public.job_post_event(jsonb) IS
  'P3 招工业务编排函数（DL20 提案 A；硬约束 DL141–DL144）。op=publish|refund|settle；幂等键由本函数按 §8 确定性派生（cli: 创建 / biz: 业务）；同一语句内完成「锁业务行 → 派生分录 → 调 ledger_post_event($1::jsonb) → 回写 ledger_event_keys/引用列」；函数体内无任何 DDL（DL142）；同键重放不重写业务行、不追加 ledger_event_keys 项（DL144①/DL149）。';


-- ============================================================================
-- §F apply-time 自检（DL48：不通过则整迁移回滚、不写版本行）
-- ============================================================================
DO $$
DECLARE
  v_missing text;
  v_cols    int;
  v_idx     int;
  v_plan    jsonb;
  v_bal     numeric;
  v_kinds   text;
  v_bad     int;
BEGIN
  -- ---------------------------------------------------------------- 结构断言
  IF to_regclass('public.job') IS NULL THEN
    RAISE EXCEPTION '0013 self-check FAILED: public.job missing';
  END IF;

  SELECT count(*) INTO v_cols
    FROM information_schema.columns c
   WHERE c.table_schema = 'public' AND c.table_name = 'job';
  IF v_cols <> 14 THEN
    RAISE EXCEPTION '0013 self-check FAILED: public.job has % columns, expected 14 (DL50)', v_cols;
  END IF;

  SELECT string_agg(x.n, ',' ORDER BY x.n) INTO v_missing
    FROM (VALUES ('job_id'),('employer_uid'),('worker_uid'),('cid'),('reward'),('title'),('description'),
                 ('status'),('create_key'),('escrow_txid'),('settle_txid'),('ledger_event_keys'),
                 ('time_created'),('time_updated')) AS x(n)
   WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns c
                      WHERE c.table_schema='public' AND c.table_name='job' AND c.column_name = x.n);
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '0013 self-check FAILED: public.job missing columns: %', v_missing;
  END IF;

  SELECT count(*) INTO v_idx
    FROM pg_indexes i
   WHERE i.schemaname='public' AND i.tablename='job'
     AND i.indexname IN ('idx_job_status_time','idx_job_employer','idx_job_worker');
  IF v_idx <> 3 THEN
    RAISE EXCEPTION '0013 self-check FAILED: expected 3 job indexes (DL53), found %', v_idx;
  END IF;

  IF to_regprocedure('public.job_post_event(jsonb)') IS NULL
     OR to_regprocedure('public.job_settle_plan(bigint,bigint,bigint,bigint,bigint)') IS NULL
     OR to_regprocedure('public.job_status_transition_ok(text,text)') IS NULL THEN
    RAISE EXCEPTION '0013 self-check FAILED: orchestration/derivation functions missing';
  END IF;

  -- DL142：编排函数体内禁 DDL（实例级 + 类级双查；类级由 p3s1b-01 覆盖全树）
  --   注：匿名块的探测串必须用 chr(36) 拼出 —— 本块自身是 dollar-quoted body，
  --   体内出现字面量 dollar-quote 标记会**提前闭合**该 body（实测：42601 syntax error）。
  SELECT string_agg(t.p, ',') INTO v_missing FROM (
    VALUES ('create table'),('alter table'),('drop table'),('truncate'),('create index'),
           ('create function'),('rename to'),('do ' || chr(36) || chr(36))
  ) AS t(p)
   WHERE position(upper(t.p) in upper(pg_get_functiondef('public.job_post_event(jsonb)'::regprocedure))) > 0;
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '0013 self-check FAILED: DDL token(s) inside job_post_event body: %', v_missing;
  END IF;

  -- ---------------------------------------------------------------- 纯函数断言（状态机白名单）
  IF NOT public.job_status_transition_ok('open','accepted')
     OR NOT public.job_status_transition_ok('open','cancelled')
     OR NOT public.job_status_transition_ok('accepted','submitted')
     OR NOT public.job_status_transition_ok('accepted','rejected')
     OR NOT public.job_status_transition_ok('submitted','settled')
     OR NOT public.job_status_transition_ok('submitted','rejected')
     OR NOT public.job_status_transition_ok('submitted','disputed')
     OR NOT public.job_status_transition_ok('disputed','settled')
     OR NOT public.job_status_transition_ok('disputed','cancelled') THEN
    RAISE EXCEPTION '0013 self-check FAILED: whitelist missing an allowed transition (DL51)';
  END IF;
  IF public.job_status_transition_ok('open','settled')
     OR public.job_status_transition_ok('open','submitted')
     OR public.job_status_transition_ok('accepted','settled')
     OR public.job_status_transition_ok('settled','open')
     OR public.job_status_transition_ok('cancelled','open')
     OR public.job_status_transition_ok('rejected','submitted')
     OR public.job_status_transition_ok('settled','cancelled') THEN
    RAISE EXCEPTION '0013 self-check FAILED: whitelist admits a forbidden transition (DL51)';
  END IF;

  -- ---------------------------------------------------------------- 结算派生守恒（只读、无副作用的纯派生）
  v_plan := public.job_settle_plan(0::bigint, 900000::bigint, 900001::bigint, 1::bigint, 10000::bigint);
  v_bal := 0;
  SELECT COALESCE(sum((t.e->>'delta')::numeric + (t.e->>'frozen_delta')::numeric), 0) INTO v_bal
    FROM jsonb_array_elements(v_plan->'entries') AS t(e);
  IF v_bal <> 0 THEN
    RAISE EXCEPTION '0013 self-check FAILED: settle entries not balanced (sum=%)', v_bal;
  END IF;
  IF (v_plan->>'fee')::numeric + (v_plan->>'net')::numeric <> (v_plan->>'gross')::numeric THEN
    RAISE EXCEPTION '0013 self-check FAILED: net + fee <> gross (CR39)';
  END IF;
  SELECT string_agg(DISTINCT t.e->>'kind', ',' ORDER BY t.e->>'kind') INTO v_kinds
    FROM jsonb_array_elements(v_plan->'entries') AS t(e);
  SELECT count(*) INTO v_bad
    FROM jsonb_array_elements(v_plan->'entries') AS t(e)
   WHERE t.e->>'kind' NOT IN ('job_payout', 'job_fee', 'commission');
  IF COALESCE(v_bad, 0) <> 0 THEN
    RAISE EXCEPTION '0013 self-check FAILED: settle event kind whitelist violated: % (kinds=%)', v_bad, v_kinds;
  END IF;

  RAISE NOTICE '0013 self-check OK: job columns=%, indexes=%, settle fee=% net=% M=% fee_credit_uid=% kinds=%',
    v_cols, v_idx, v_plan->>'fee', v_plan->>'net', v_plan->>'M', v_plan->>'fee_credit_uid', v_kinds;
END $$;

