-- C1 状态转移白名单（DL51 / DL52①）
CREATE OR REPLACE FUNCTION public.job_status_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NOT public.job_status_transition_ok(OLD.status, NEW.status) THEN
      PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
        jsonb_build_object('field', 'job.status', 'reason', 'JOB_STATE_INVALID',
                           'from', OLD.status, 'to', NEW.status, 'job_id', OLD.job_id::text));
    END IF;
  END IF;
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_status_guard() IS
  'DL52① / DL51：状态转移白名单（唯一真源 = public.job_status_transition_ok）。违反 ⇒ 借码 LD011 LEDGER_CURRENCY_INVALID_TRANSITION（integrity ⇒ 409）+ reason=JOB_STATE_INVALID（大写为唯一口径）。';

-- C2 账本引用列一次写定（DL52②；`OLD IS NULL` 时允许写入，之后禁改、禁清空）
CREATE OR REPLACE FUNCTION public.job_ledger_ref_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.escrow_txid IS NOT NULL AND NEW.escrow_txid IS DISTINCT FROM OLD.escrow_txid THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job.escrow_txid', 'reason', 'job_ledger_ref_immutable',
                         'old', OLD.escrow_txid::text,
                         'new', CASE WHEN NEW.escrow_txid IS NULL THEN NULL ELSE NEW.escrow_txid::text END,
                         'job_id', OLD.job_id::text));
  END IF;
  IF OLD.settle_txid IS NOT NULL AND NEW.settle_txid IS DISTINCT FROM OLD.settle_txid THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job.settle_txid', 'reason', 'job_ledger_ref_immutable',
                         'old', OLD.settle_txid::text,
                         'new', CASE WHEN NEW.settle_txid IS NULL THEN NULL ELSE NEW.settle_txid::text END,
                         'job_id', OLD.job_id::text));
  END IF;
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_ledger_ref_guard() IS
  'DL52②：escrow_txid / settle_txid 一次写定（OLD 非 NULL 后禁改、禁清空）。护栏强度=行触发器；不拦 TRUNCATE / DISABLE TRIGGER USER。';

-- C3 核心业务字段冻结（DL52③）+ worker/create_key 一次写定（防「托管后改价」）
CREATE OR REPLACE FUNCTION public.job_core_immutable_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status <> 'open'
     AND (NEW.employer_uid IS DISTINCT FROM OLD.employer_uid
          OR NEW.cid       IS DISTINCT FROM OLD.cid
          OR NEW.reward    IS DISTINCT FROM OLD.reward) THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job.core_fields', 'reason', 'job_core_fields_immutable',
                         'status', OLD.status, 'job_id', OLD.job_id::text));
  END IF;
  IF OLD.worker_uid IS NOT NULL AND NEW.worker_uid IS DISTINCT FROM OLD.worker_uid THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job.worker_uid', 'reason', 'job_worker_immutable',
                         'old', OLD.worker_uid::text,
                         'new', CASE WHEN NEW.worker_uid IS NULL THEN NULL ELSE NEW.worker_uid::text END,
                         'job_id', OLD.job_id::text));
  END IF;
  IF NEW.create_key IS DISTINCT FROM OLD.create_key THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job.create_key', 'reason', 'job_create_key_immutable',
                         'job_id', OLD.job_id::text));
  END IF;
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_core_immutable_guard() IS
  'DL52③：employer_uid / cid / reward 在 status <> ''open'' 后不可变（防托管后改价）；worker_uid 选定后一次写定；create_key 永不可改。';

-- C4 时间戳统一刷新（DL75③：不接受客户端传时间，R5）
CREATE OR REPLACE FUNCTION public.job_touch_time_updated() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.time_updated := now();
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_touch_time_updated() IS
  'DL75③ / R5：time_updated 由 BEFORE UPDATE 触发器统一刷新，不接受客户端传时间。';

-- C5 禁 DELETE（DL79：业务行的终结 = 状态位）
CREATE OR REPLACE FUNCTION public.job_no_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
    jsonb_build_object('field', 'job', 'reason', 'job_delete_forbidden', 'job_id', OLD.job_id::text));
END $$;

COMMENT ON FUNCTION public.job_no_delete() IS
  'DL79：业务表禁物理删除（终结 = status 位）。触发器执行序按名字母序：core_immutable → ledger_ref → status → touch。';

