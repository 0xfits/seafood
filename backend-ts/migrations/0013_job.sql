-- ============================================================================
-- §A 状态机白名单（DL51）—— 唯一真源，供触发器与编排函数共用
-- ============================================================================
CREATE OR REPLACE FUNCTION public.job_status_transition_ok(p_from text, p_to text)
RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p_from
    WHEN 'open'      THEN p_to IN ('accepted', 'cancelled')
    WHEN 'accepted'  THEN p_to IN ('submitted', 'rejected')
    WHEN 'submitted' THEN p_to IN ('settled', 'rejected', 'disputed')
    WHEN 'disputed'  THEN p_to IN ('settled', 'cancelled')
    ELSE false            -- settled / rejected / cancelled = 无出边（终态；rejected 在白名单里无后继）
  END
$$;

COMMENT ON FUNCTION public.job_status_transition_ok(text, text) IS
  'DL51 状态机白名单唯一真源：open→{accepted,cancelled}；accepted→{submitted,rejected}；submitted→{settled,rejected,disputed}；disputed→{settled,cancelled}；settled/cancelled/rejected 无出边。';


-- ============================================================================
-- §B `public.job` 表（逐列照 §6.2 / DL50）
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.job (
  job_id             bigint      GENERATED BY DEFAULT AS IDENTITY,
  employer_uid       bigint      NOT NULL,
  worker_uid         bigint,
  cid                bigint      NOT NULL,
  reward             bigint      NOT NULL,
  title              text        NOT NULL DEFAULT '',
  description        text        NOT NULL DEFAULT '',
  status             text        NOT NULL DEFAULT 'open',
  create_key         text        NOT NULL,
  escrow_txid        bigint,
  settle_txid        bigint,
  ledger_event_keys  text[]      NOT NULL DEFAULT '{}',
  time_created       timestamptz NOT NULL DEFAULT now(),
  time_updated       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT job_pk              PRIMARY KEY (job_id),
  -- 三件套 ①（DL75 / DL50）：创建幂等键，指纹口径与 R51/R52 一致
  CONSTRAINT job_create_key_uniq UNIQUE (create_key),
  -- DL50：`reward` 是业务约定额（不是余额，DL3）
  CONSTRAINT job_reward_positive CHECK (reward > 0),
  -- DL51 状态白名单（§6.2 的 7 态；`disputed` 属 P6 仲裁路径，列先进关闭集）
  CONSTRAINT job_status_enum     CHECK (status IN ('open','accepted','submitted','settled','disputed','rejected','cancelled')),
  CONSTRAINT job_employer_fk     FOREIGN KEY (employer_uid) REFERENCES public.users(uid),
  CONSTRAINT job_worker_fk       FOREIGN KEY (worker_uid)   REFERENCES public.users(uid),
  CONSTRAINT job_cid_fk          FOREIGN KEY (cid)          REFERENCES public.currency(cid)
);

COMMENT ON TABLE public.job IS
  'P3 招工第一柱主表（data-layer.spec v0.3 §6.2 / DL50）。账本引用列 escrow_txid/settle_txid 不建 FK（R21 方向：反向引用用 bigint + 对账）。';

-- DL53：三个必建索引（`create_key` 的唯一约束自带索引，不另建）
