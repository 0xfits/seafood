    FROM information_schema.columns
   WHERE table_schema = 'public' AND table_name = 'admin_refund_audit_log';
  IF v_names <> 'log_id,actor_uid,order_id,seller_uid,buyer_uid,cid,amount,result,txid,idempotency_key,request_fingerprint,memo,time_created' THEN
    RAISE EXCEPTION '0024 self-check FAILED: admin_refund_audit_log columns = %', v_names;
  END IF;

  -- 具名约束齐：PK×1 / FK×4 / CHECK×2 / UNIQUE×1
  SELECT count(*) INTO v_n FROM pg_constraint WHERE conrelid = 'public.admin_refund_audit_log'::regclass AND contype = 'p';
