-- ============================================================================
-- §C 唯一资金写路径编排函数（Z4；同构 `admin_points_adjust_post_event`）
-- ============================================================================
-- 调用方**一条语句**：`SELECT public.listing_refund_post_event($1::jsonb)`
--   （经 `DatabaseService.listingRefundPostEvent`）。
-- 函数内三段（同一函数、同一条语句 = 一个隐式事务）：
--   ① （无 advisory lock · Z4b）
--   ② 调**既有** `public.listing_post_event(payload)`（`op='refund'`；**函数体一字不改**）
--   ③ 写审计行 `INSERT INTO public.admin_refund_audit_log …`
-- ⇒ **审计行与资金事件同生同灭**（不存在「资金动了而审计没落」或反之）。
--
-- ★ 拒绝面（Z3 / T-2 / §12.12.3）：状态机拒绝（`0015:682-690` 的
--   `ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION', …)` = SQLSTATE `LD011`）由**子事务**捕获；
--   白名单 = `reason ∈ {order_not_refundable, order_pay_missing}` ⇒ 写 `result='rejected_state'`
--   审计行（**落在 EXCEPTION 处理器内** ⇒ 子事务回滚**不波及**它）+ 返回拒收回执。
--   **只捕 `LD011` 一类**（严禁 `WHEN OTHERS`）⇒ 其他 SQLSTATE（含 `53300`/`XX000` 基础设施错、
--   `LD022` 404）**保持既有传播**、由既有 §14 分类器映射。
-- ★ 本函数体内**无任何** `RAISE`（异常会回滚同函数内已写的拒绝留痕行）。
-- ★ 本函数体内**不得出现** `purchase_refund` 字面量（AC-12：防双真源）。
CREATE OR REPLACE FUNCTION public.listing_refund_post_event(payload jsonb) RETURNS jsonb
LANGUAGE plpgsql AS $$
DECLARE
  v_actor     bigint := (payload->>'actor_uid')::bigint;
  v_fp        text   := payload->>'request_fingerprint';
  v_memo      text   := COALESCE(NULLIF(payload->>'memo', ''), 'listing refund');
  v_order_id  bigint := public.ledger_int_amount(COALESCE(payload->>'order_id', ''), 'order_id');
  v_key       text   := 'biz:listing:refund:' || v_order_id::text;
  v_envelope  jsonb;
  v_ledger    jsonb;
  v_txid      text;
  v_replay    boolean := false;
  v_seller    bigint;
  v_buyer     bigint;
  v_cid       bigint;
  v_amount    bigint;
  v_audited   boolean := false;
  v_detail    text;
  v_reason    text;
BEGIN
  -- ---------------------------------------------------------------- ② 资金事件（既有账本函数；同一语句内）
  -- **信封逐字同改接前的服务层 payload**（`op` / `order_id` / `request_fingerprint` / `memo`）；
  -- 金额 / 对手方 / 幂等键 / 状态机一律由 `listing_post_event`（`0015`）服务端取数 ⇒ 本函数
  -- **不派生任何分录、不构造任何资金腿**。
  v_envelope := jsonb_build_object(
    'op',                  'refund',
    'order_id',            v_order_id::text,
    'request_fingerprint', v_fp,
    'memo',                v_memo);

  BEGIN
    v_ledger := public.listing_post_event(v_envelope);
  EXCEPTION WHEN SQLSTATE 'LD011' THEN
    -- ★ 白名单式捕获（严禁兜底类子句）：只认「状态机拒绝」那两种 reason。
    --   `reason` 的载体 = `ledger_raise` 的 `DETAIL`（`0004:148`）；读取手法照抄 `0004:1094`。
    --   用正则取值（**不用** JSON 解析 ⇒ 无需任何兜底类子句）。
    GET STACKED DIAGNOSTICS v_detail = PG_EXCEPTION_DETAIL;
    v_reason := substring(v_detail from '"reason"[[:space:]]*:[[:space:]]*"([^"]*)"');

    IF v_reason IN ('order_not_refundable', 'order_pay_missing') THEN
      -- 审计行取值 = **订单行服务端取数**（§12.11.3；拒绝行无资金回执）。
      -- 资金腿已随子事务回滚 ⇒ **零资金残留**；本插入在处理器内 ⇒ **不受该回滚波及**。
      SELECT o.seller_uid, o.buyer_uid, o.cid, (o.price * o.quantity)::bigint
        INTO v_seller, v_buyer, v_cid, v_amount
        FROM public.listing_order AS o
       WHERE o.order_id = v_order_id;

      IF FOUND THEN
        INSERT INTO public.admin_refund_audit_log
          (actor_uid, order_id, seller_uid, buyer_uid, cid, amount,
           result, txid, idempotency_key, request_fingerprint, memo)
        VALUES
          (v_actor, v_order_id, v_seller, v_buyer, v_cid, v_amount,
           'rejected_state', NULL, v_key, v_fp, v_reason)
        ON CONFLICT (idempotency_key, result) DO NOTHING;

        RETURN jsonb_build_object(
          'ok', false, 'order_id', v_order_id::text, 'reason', v_reason,
          'status_field', 'listing_order.status',
          'txid', NULL, 'idempotent_replay', false,
          'audit_logged', true, 'result', 'rejected_state');
      END IF;
    END IF;

    -- 非白名单 `LD011`（例如币种状态位拒绝 `{cid,from,to}`）/ 订单行缺失：
    -- **不写审计行**（Z3 射程 = 白名单状态位拒绝），只回**未被拒收回执** ⇒ 由路由映射既有 `409`。
    RETURN jsonb_build_object(
      'ok', false, 'order_id', v_order_id::text, 'reason', v_reason,
      'status_field', 'listing_order.status',
      'txid', NULL, 'idempotent_replay', false,
      'audit_logged', false, 'result', NULL);
  END;

  v_txid   := v_ledger->>'txid';
  v_replay := COALESCE((v_ledger->>'idempotent_replay')::boolean, false);

  -- ---------------------------------------------------------------- ③ 审计行（与资金同函数、同语句）
  -- DL144① 同精神：**重放 ⇒ 不写第二行审计**（同时被 `admin_refund_audit_log_idem_uniq` 兜住）。
  IF NOT v_replay THEN
    -- 取值 = **资金回执**（服务端取数；不重复读订单行 ⇒ 审计与资金**同源**）：
    --   卖方腿 = 负 delta 那条；买方腿 = 正 delta 那条；金额 = |delta|。
    SELECT (e->>'uid')::bigint, (e->>'cid')::bigint, (-((e->>'delta')::bigint))
      INTO v_seller, v_cid, v_amount
      FROM jsonb_array_elements(v_ledger->'entries') AS t(e)
     WHERE (e->>'delta')::bigint < 0
     LIMIT 1;
    SELECT (e->>'uid')::bigint
      INTO v_buyer
      FROM jsonb_array_elements(v_ledger->'entries') AS t(e)
     WHERE (e->>'delta')::bigint > 0
     LIMIT 1;

    -- `idempotency_key` = 资金事件根键**逐字**（直接取回执字段，不自行拼接）。
    v_key := COALESCE(v_ledger->>'ledger_idempotency_key', v_key);

    INSERT INTO public.admin_refund_audit_log
      (actor_uid, order_id, seller_uid, buyer_uid, cid, amount,
       result, txid, idempotency_key, request_fingerprint, memo)
    VALUES
      (v_actor, v_order_id, v_seller, v_buyer, v_cid, v_amount,
       'applied', v_txid::bigint, v_key, v_fp, v_memo);
    v_audited := true;
  END IF;

  RETURN jsonb_build_object(
    'ok', true, 'order_id', v_order_id::text,
    'txid', v_txid, 'idempotent_replay', v_replay,
    'audit_logged', v_audited, 'result', 'applied',
    'refund_receipt', v_ledger);
END $$;

COMMENT ON FUNCTION public.listing_refund_post_event(jsonb) IS
  'P7-B（Z4 / Z4b / T-2；硬约束 = 防双真源）：§7-32「管理员退款发起」的**唯一资金写路径**。同一函数 / 同一语句内完成「调**既有** public.listing_post_event(op=''refund'')（**复用资金腿**：purchase_refund ×2 / 金额服务端取数 / 不回滚库存全在 0015）→ 写 public.admin_refund_audit_log」⇒ **审计行与资金事件同生同灭**。**不取 pg_advisory_xact_lock**（Z4b；同订单串行性由 0015:670 的 FOR UPDATE 行锁承担）。拒绝面 = 子事务内捕获 SQLSTATE ''LD011'' 且 reason ∈ {order_not_refundable, order_pay_missing}（白名单；严禁兜底类子句）⇒ 写 result=''rejected_state'' 审计行（落在 EXCEPTION 处理器内 ⇒ 子事务回滚不波及）+ 返回拒收回执，由路由映射 409 LD011。**本函数体内无任何 RAISE**、**无 purchase_refund 字面量**、**无 WHEN OTHERS**。同键重投 ⇒ ON CONFLICT (idempotency_key, result) DO NOTHING。';


