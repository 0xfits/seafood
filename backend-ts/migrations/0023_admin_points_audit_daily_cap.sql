CREATE OR REPLACE FUNCTION public.admin_ops_audit_log_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'admin_ops_audit_log is append-only: % forbidden (log_id=%)',
        TG_OP, COALESCE(OLD.log_id, 0);
END $$;

COMMENT ON FUNCTION public.admin_ops_audit_log_append_only() IS
  'P6-B6-AUDIT：审计表 append-only（BEFORE UPDATE OR DELETE 无条件 RAISE，原生 P0001，不借账本错误码 ⇒ 不建账本类对象）。只由迁移创建；体内无 DDL。诚实边界：不拦 TRUNCATE / DISABLE TRIGGER USER。';

DROP TRIGGER IF EXISTS trg_admin_ops_audit_log_append_only ON public.admin_ops_audit_log;
CREATE TRIGGER trg_admin_ops_audit_log_append_only
  BEFORE UPDATE OR DELETE ON public.admin_ops_audit_log
  FOR EACH ROW EXECUTE FUNCTION public.admin_ops_audit_log_append_only();

