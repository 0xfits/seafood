-- ============================================================================
-- §A `public.admin_ops_audit_log`（管理面越权/资金动作审计；逐列标依据见交付报告 §1）
-- ============================================================================
-- 命名/列风格参照 `0017` 的 `public.currency_status_log`（7 列 + 身份证 PK + 具名约束 + append-only）。
-- 列清单（谁 / 何时 / 对谁 / 动作 / 值前值 / 请求指纹 / 幂等键 / 结果）：
--   who   = actor_uid                     ；when = time_created   ；whom = target_uid
--   act   = action / op / cid             ；value = amount + balance_before / balance_after
--   proof = request_fingerprint（DL96）+ idempotency_key（DL146② / DL36 `ops:` 系）
--   result= result（'applied' | 'rejected_daily_cap'）+ txid（账本回执）
CREATE TABLE IF NOT EXISTS public.admin_ops_audit_log (
  log_id              bigint      GENERATED BY DEFAULT AS IDENTITY,          -- 依据 0017:140 先例（身份证 PK）
  actor_uid           bigint      NOT NULL,                                   -- 依据 §4.10③ requireAdmin ⇒ 操作人；
                                                                              --   日累计口径「按操作人」（Zang 新定）
  action              text        NOT NULL,                                   -- 依据 §4.8⑨② 「授权主体意图额」逐动作留痕；
                                                                              --   本仓 A1 = 'points_adjust'
  target_uid          bigint      NOT NULL,                                   -- 依据 §4.10③ `uID` ⇒「对谁」
  cid                 bigint      NOT NULL,                                   -- 依据现盘 A1 恒 `cid=1`（database.ts:1066 ref_id '1'）
  op                  text        NOT NULL,                                   -- 依据 §4.10③ 符号派生 ⇒ 'mint' | 'burn'
  amount              bigint      NOT NULL,                                   -- 依据 §4.10③ **有符号** amount（值）
  balance_before      numeric,                                                -- 依据「值前值」要求；= 事后余额 − amount（账本回执推导）
  balance_after       numeric,                                                -- 依据「值前值」要求；= 账本回执 accounts[].balance
  request_fingerprint text        NOT NULL,                                   -- 依据 DL96（index.ts:1268 现盘）
  idempotency_key     text        NOT NULL,                                   -- 依据 DL146② / §4.8（`ops:` 系；index.ts:1264 现盘）
  result              text        NOT NULL,                                   -- 依据「结果」列要求 + Zang 裁定①（拒绝亦须留痕）
  txid                bigint,                                                 -- 依据账本回执 `txid`（成功时；拒绝行 = NULL）
  memo                text,                                                   -- 依据 0017:145 `currency_status_log.memo` 先例（= reason）
  time_created        timestamptz NOT NULL DEFAULT now(),                     -- 依据 0017:146 先例；日累计「自然日（UTC）」判据列
  CONSTRAINT admin_ops_audit_log_pk         PRIMARY KEY (log_id),
  CONSTRAINT admin_ops_audit_log_actor_fk   FOREIGN KEY (actor_uid)  REFERENCES public.users(uid),
  CONSTRAINT admin_ops_audit_log_target_fk  FOREIGN KEY (target_uid) REFERENCES public.users(uid),
  CONSTRAINT admin_ops_audit_log_cid_fk     FOREIGN KEY (cid)        REFERENCES public.currency(cid),
  CONSTRAINT admin_ops_audit_log_action_ck CHECK (action = 'points_adjust'),
  CONSTRAINT admin_ops_audit_log_op_ck     CHECK (op IN ('mint', 'burn')),
  CONSTRAINT admin_ops_audit_log_amount_ck CHECK (amount <> 0),
  CONSTRAINT admin_ops_audit_log_result_ck CHECK (result IN ('applied', 'rejected_daily_cap')),
  -- ★ Zang 裁定四（BE-AUDIT-FIX2）：幂等键的语义约束「**效果**」、不约束「**尝试**」。
  -- 旧写法 `UNIQUE (idempotency_key)` 对成功行与拒绝行**一视同仁** ⇒ **被拒的键即被消费**：
  --   额度释放后客户端拿**同一个键**重投 ⇒ 末尾 `'applied'` 插入撞上既有拒绝行 ⇒ `23505` ⇒
  --   **整条语句回滚**（客户端拿到莫名的约束错误）。
  -- 改法 `UNIQUE (idempotency_key, result)` —— 一个索引同时把三向都修对：
  --   ① 同键被拒两次 ⇒ `(key,'rejected_daily_cap')` 冲突 ⇒ `DO NOTHING`（**拒绝行不放大**）；
  --   ② 同键先拒后成 ⇒ `result` 不同 ⇒ **允许成功**（且既有拒绝行保留）；
  --   ③ 同键成功两次 ⇒ `(key,'applied')` 冲突 ⇒ **拦住**（真幂等保护不弱化）。
  -- 结论位对「同键 + 同结果」唯一：同键**不得**产生第二行**同结果**审计（DL146② 兜底不弱化）。
  CONSTRAINT admin_ops_audit_log_idem_uniq UNIQUE (idempotency_key, result)
);

COMMENT ON TABLE public.admin_ops_audit_log IS
  'P6-B6-AUDIT（Kong；依据 route-layer.spec §4.8⑨② + §4.10③，Zang 2026-10-02 新定 + 三条裁定）：管理面「授权主体意图额」类动作（本仓 A1 = 后台调分）的**审计留痕**。列风格参照 0017.currency_status_log（身份证 PK + 具名约束 + append-only）。**只增不删**：BEFORE UPDATE OR DELETE 无条件 RAISE。actor_uid/target_uid FK users(uid)、cid FK currency(cid)。**成功行与拒绝行同表**（`result` 区分）。诚实边界：append-only 触发器不拦 TRUNCATE / DISABLE TRIGGER USER（与 0017 同边界）。';

COMMENT ON COLUMN public.admin_ops_audit_log.balance_before IS
  '值前值（余额）。账本回执只给事后余额 ⇒ 本列 = balance_after − amount（同一函数内推导，非外部传入）。**拒绝行 = NULL**（无资金事件）。';
COMMENT ON COLUMN public.admin_ops_audit_log.result IS
  '结论位。''applied'' = 资金事件已落且本审计行与它同语句（**计入**当日累计）；''rejected_daily_cap'' = 日累计闸拒绝的**留痕**行（Zang 裁定①：被拒尝试必须留痕）——**零资金分录**、balance_before/balance_after/txid 皆 NULL、memo=OVER_MAX_DAILY_AMOUNT，且**不计入**日累计求和（裁定②：只对 result=''applied'' 求和，防「反复发超限请求把当日额度刷爆」）。';


