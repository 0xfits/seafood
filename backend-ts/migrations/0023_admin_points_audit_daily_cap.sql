-- ============================================================================
-- §C 唯一资金写路径编排函数（DL20 提案 A；硬约束 DL141–DL144）
-- ============================================================================
-- 与 `public.job_post_event(jsonb)` **同构**：调用方一条语句 `SELECT public.admin_points_adjust_post_event($1::jsonb)`
-- ⇒ 函数内「并发闸 → 存在性闸 → 日累计闸 → 派生分录 → 调 ledger_post_event → 写审计行 → 回执」
--    **同函数、同语句**（= 一个隐式事务）。
-- 回执形状（全部为 jsonb 标量，路由层用 `->>` 取值 ⇒ 不依赖 TS 侧 JSON 解析）：
--   { ok, user_found, reason, op, amount, idempotent_replay, txid, new_balance, audit_logged,
--     daily_cap, daily_used, entries, accounts }
--   · 拒绝回执（Zang 裁定①，**函数正常返回、不 RAISE**）：
--     { ok:false, user_found:1, reason:'OVER_MAX_DAILY_AMOUNT', op, requested, daily_cap, daily_used }
-- 契约：
--   · `user_found = 0` ⇒ 库内无该目标用户 ⇒ **零写**（不调账本、不写审计），由路由映射既有码 LD021。
--   · `ok = false` + `reason = 'OVER_MAX_DAILY_AMOUNT'` ⇒ 日累计闸拒 ⇒ **零资金分录、留一行审计**
--     （`result='rejected_daily_cap'`，与「无资金分录」一起提交）。**函数不得 `RAISE`**：异常会把同一
--     函数内**已写的拒绝审计行**一并回滚（被拒尝试恰恰最该留痕）；故本分支**正常返回拒绝回执**，
--     由路由层据此回 `400` + 既有码 LD016（`LEDGER_AMOUNT_INVALID`）+ 机读 `reason`（裁定③：零新码）。
--   · 成功 ⇒ 资金事件与审计行**同生**；同键同指纹重放 ⇒ `idempotent_replay=true` 且**不写第二行审计**。
CREATE OR REPLACE FUNCTION public.admin_points_adjust_post_event(payload jsonb) RETURNS jsonb
LANGUAGE plpgsql AS $$
DECLARE
  -- ★★ 服务端常量（**客户端永不参与**）：日累计上限 = 1,000,000 点/日，按操作人 + 自然日（UTC）。
  -- TODO: Kevin 定值
  v_daily_cap   CONSTANT bigint := 1000000;

  v_actor       bigint := (payload->>'actor_uid')::bigint;
  v_target      bigint := (payload->>'target_uid')::bigint;
  v_cid         bigint := COALESCE((payload->>'cid')::bigint, 1);
  v_amount      bigint := (payload->>'amount')::bigint;
  v_reason      text   := COALESCE(payload->>'reason', '');
  v_key         text   := payload->>'idempotency_key';
  v_fp          text   := payload->>'request_fingerprint';

  v_day_start   timestamptz := date_trunc('day', now() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
  v_used        bigint;
  v_op          text;
  v_envelope    jsonb;
  v_ledger      jsonb;
  v_txid        text;
  v_replay      boolean := false;
  v_new_balance numeric;
  v_bal_before  numeric;
  v_audited     boolean := false;
BEGIN
  -- ---------------------------------------------------------------- ① 并发闸（同一语句内）
  -- 按操作人取事务级 advisory lock ⇒ 同一操作人的并发两笔**串行**：后到者读到前者的已提交审计行
  -- ⇒ 「两笔同时卡在阈值下」的竞态被消除（恰一笔过、另一笔被日累计拒）。
  PERFORM pg_advisory_xact_lock(hashtextextended('admin_points_adjust:' || v_actor::text, 0));

  -- ---------------------------------------------------------------- ② 目标存在性闸（零写）
  IF NOT EXISTS (SELECT 1 FROM public."users" AS u WHERE u.uid = v_target) THEN
    RETURN jsonb_build_object('ok', false, 'user_found', 0, 'reason', NULL,
                              'daily_cap', v_daily_cap, 'daily_used', NULL);
  END IF;

  -- ---------------------------------------------------------------- ③ 符号 ⇒ op（提前派生）
  -- 拒绝行也须携带**合法 op**（CHECK `op IN ('mint','burn')` 对两类结果行一视同仁）⇒ 在日累计闸
  -- **之前**派生，使「被拒尝试」的审计行与成功行同形（只差 `result` / `txid` / 余额两列）。
  IF v_amount > 0 THEN v_op := 'mint'; ELSE v_op := 'burn'; END IF;

  -- ---------------------------------------------------------------- ③' 日累计闸（同函数内读当日审计行求和）
  -- ★ 求和口径（逐字，Zang 裁定②）：`actor_uid = v_actor` 且 **`result = 'applied'`（只计成功行）**
  --   且 `time_created >= 当日 00:00 UTC` 的 `abs(amount)` 之和。
  -- ★ 为何必须排除拒绝行：被拒行同样携带 `amount`（= 请求值，非零）；若把它计入求和，则**反复发
  --   超限请求即可把当日额度刷爆**（每笔被拒都在「已用」上再加一笔）⇒ 管理员当天再也调不出分
  --   = 拒绝留痕引入的新攻击面。故**只计成功行**（`result = 'applied'`）。
  -- `idempotency_key <> v_key`：把**本次键的既有行**排除 ⇒ 同键重放不会被自己顶穿（否则 900k 的重放
  --   会因 900k+900k > cap 被误拒）；对**新键**而言该排除项不命中 ⇒ 判定不变。
  SELECT COALESCE(sum(abs(a.amount)), 0)::bigint INTO v_used
    FROM public.admin_ops_audit_log AS a
   WHERE a.actor_uid  = v_actor
     AND a.result     = 'applied'
     AND a.time_created >= v_day_start
     AND a.idempotency_key <> v_key;

  IF v_used + abs(v_amount) > v_daily_cap THEN
    -- 拒绝留痕（Zang 裁定①）：写审计行 `result='rejected_daily_cap'`，**与「零资金分录」一起提交**。
    -- **不得以异常中止**：异常会把同一函数内**已写的这一行**一并回滚（被拒尝试恰恰最该留痕）；
    -- 且本仓不落 access log ⇒ 只写服务端日志等于无痕迹。故此处**正常返回拒绝回执**。
    -- 同键重投 ⇒ `ON CONFLICT DO NOTHING` ⇒ **不重复写审计行**（与「幂等」口径一致）。
    INSERT INTO public.admin_ops_audit_log
      (actor_uid, action, target_uid, cid, op, amount, balance_before, balance_after,
       request_fingerprint, idempotency_key, result, txid, memo)
    VALUES
      (v_actor, 'points_adjust', v_target, v_cid, v_op, v_amount, NULL, NULL,
       v_fp, v_key, 'rejected_daily_cap', NULL, 'OVER_MAX_DAILY_AMOUNT')
    ON CONFLICT (idempotency_key, result) DO NOTHING;
    RETURN jsonb_build_object('ok', false, 'user_found', 1, 'reason', 'OVER_MAX_DAILY_AMOUNT',
                              'op', v_op, 'requested', v_amount::text,
                              'daily_cap', v_daily_cap, 'daily_used', v_used);
  END IF;

  -- ---------------------------------------------------------------- ④ 派生分录（§4.10③ 逐字；op 已在 ③ 派生）
  IF v_op = 'mint' THEN
    v_envelope := jsonb_build_object(
      'op', 'mint', 'idempotency_key', v_key, 'request_fingerprint', v_fp, 'memo', v_reason,
      'ref_type', 'currency', 'ref_id', v_cid::text,
      'uid', v_target::text, 'cid', v_cid::text, 'amount_units', v_amount::text, 'platform', true);
  ELSE
    v_envelope := jsonb_build_object(
      'op', 'entries', 'idempotency_key', v_key, 'request_fingerprint', v_fp, 'memo', v_reason,
      'ref_type', 'currency', 'ref_id', v_cid::text,
      'entries', jsonb_build_array(jsonb_build_object(
        'uid', v_target::text, 'cid', v_cid::text, 'delta', v_amount::text, 'kind', 'burn')));
  END IF;

  -- ---------------------------------------------------------------- ⑤ 资金事件（既有账本函数；同一语句内）
  -- 锁序：advisory（本函数）→ currency（cid 升序）→ account（uid 升序）—— 后两段由 ledger_post_event
  -- 内部完成；本函数**绝不**先锁 account（否则 AB-BA 死锁）。
  v_ledger := public.ledger_post_event(v_envelope);
  v_txid   := v_ledger->>'txid';
  v_replay := COALESCE((v_ledger->>'idempotent_replay')::boolean, false);

  SELECT (e->>'balance')::numeric INTO v_new_balance
    FROM jsonb_array_elements(v_ledger->'accounts') AS t(e)
   WHERE (e->>'uid')::bigint = v_target AND (e->>'cid')::bigint = v_cid;

  -- ---------------------------------------------------------------- ⑥ 审计行（与资金同函数、同语句）
  -- DL144① 同精神：**重放 ⇒ 不写第二行审计**（同时被 `admin_ops_audit_log_idem_uniq` 兜住）。
  IF NOT v_replay THEN
    v_bal_before := v_new_balance - v_amount;     -- 账本只给事后余额 ⇒ 前值 = 事后 − amount
    INSERT INTO public.admin_ops_audit_log
      (actor_uid, action, target_uid, cid, op, amount, balance_before, balance_after,
       request_fingerprint, idempotency_key, result, txid, memo)
    VALUES
      (v_actor, 'points_adjust', v_target, v_cid, v_op, v_amount, v_bal_before, v_new_balance,
       v_fp, v_key, 'applied', v_txid::bigint, v_reason);
    v_audited := true;
  END IF;

  RETURN jsonb_build_object(
    'ok', true, 'user_found', 1, 'reason', NULL, 'op', v_op, 'amount', v_amount::text,
    'idempotent_replay', v_replay, 'txid', v_txid,
    'new_balance', CASE WHEN v_new_balance IS NULL THEN NULL ELSE v_new_balance::text END,
    'audit_logged', v_audited, 'daily_cap', v_daily_cap, 'daily_used', v_used,
    'entries', v_ledger->'entries', 'accounts', v_ledger->'accounts');
END $$;

