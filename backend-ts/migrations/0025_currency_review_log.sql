-- ============================================================================
-- §A `public.currency_review_log`（审核台账 · append-only · 逐列照 §26.7(b)）
-- ============================================================================
-- 命名依据（§26.7(a)）：承同资源同后缀先例 `public.currency_status_log`（`0017:139`）⇒
--   资源词 `currency` + append-only 台账后缀 `_log`（`currency_status_log` /
--   `admin_ops_audit_log`（`0023:64`）/ `admin_refund_audit_log`（`0024:50`））。
-- 与既有 `currency_status_log` 的分工（§26.3）：本表 = 「**审核动作**」留痕
--   （`pending`/`approved`/`rejected`）；`currency_status_log` = 「**状态迁移**」留痕
--   （仍只记 `draft → listed` 一条边）。两者职责不重叠。
CREATE TABLE IF NOT EXISTS public.currency_review_log (
  log_id              bigint      GENERATED BY DEFAULT AS IDENTITY,          -- 0023:65 / 0024:54 / 0017:140（身份证 PK 先例）
  cid                 bigint      NOT NULL,                                   -- 0023:71 / 0017:141
  actor_uid           bigint      NOT NULL,                                   -- 0023:66 / 0024:55 / 0017:144（发起人 uid；token 侧；不得由客户端声明）
  result              text        NOT NULL,                                   -- 0023:78 / 0024:60（结论位手法；值域 = 下方 CHECK）
  request_fingerprint text        NOT NULL,                                   -- 0023:76 / 0024:58（DL96；服务端派生）
  idempotency_key     text        NOT NULL,                                   -- 0023:77 / 0024:57（DL146② / DL36 的 `ops:` 系）
  memo                text,                                                   -- 0017:145 / 0023:80 / 0024:61（驳回 = reason；可空）
  time_created        timestamptz NOT NULL DEFAULT now(),                     -- 0023:81 / 0024:62 / 0017:146（DB 生成，不得客户端传）
  CONSTRAINT currency_review_log_pk        PRIMARY KEY (log_id),                                         -- 0023:82 / 0024:64
  CONSTRAINT currency_review_log_actor_fk  FOREIGN KEY (actor_uid) REFERENCES public.users(uid),          -- 0023:83 / 0024:66
  CONSTRAINT currency_review_log_cid_fk    FOREIGN KEY (cid)       REFERENCES public.currency(cid),       -- 0023:85 / 0024:68
  CONSTRAINT currency_review_log_result_ck CHECK (result IN ('pending', 'approved', 'rejected')),         -- 0023:89（result 闭集手法）；值域 = R-8-21 给定（非本单发明）
  -- ★ 沿用 `0023` 裁定四（「幂等键的语义约束**效果**、不约束**尝试**」）：
  --   同键同 `result` 重投 ⇒ `(key, result)` 冲突 ⇒ `DO NOTHING`（幂等重放，拒绝行不放大）；
  --   同键异 `result`（先驳后成 / 先成后驳）⇒ 允许，各留一行（§23.3(a) / §26.7(c)）。
  CONSTRAINT currency_review_log_idem_uniq UNIQUE (idempotency_key, result)                               -- 0023:99 / 0024:72
);

COMMENT ON TABLE public.currency_review_log IS
  '批 8④（Kong；依据 data-layer.spec v0.15 §26.7 + route-layer.spec v2.8 §23）：自建单位（currency）**审核动作的旁路台账**（变体 Ⅱ）。列风格 / 约束命名 / 索引形态 / append-only 手法照抄 0023 的 admin_ops_audit_log。**只增不删**：BEFORE UPDATE OR DELETE 无条件 RAISE。actor_uid FK users(uid)、cid FK currency(cid)。**成功行（approved）与拒绝行（rejected）同表**（result 闭集 = {pending, approved, rejected}）。**与既有 currency_status_log 分工不重叠**：本表记「审核动作」，后者记「状态迁移」。**零 ALTER 既有表**。诚实边界：append-only 触发器不拦 TRUNCATE / DISABLE TRIGGER USER（同 0017 / 0023）。';

COMMENT ON COLUMN public.currency_review_log.result IS
  '结论位（R-8-21 给定的三态值域）。''pending'' = 待审（写入者 / 写入时机 = 待实现单，§26.2(c)）；''approved'' = 审核通过（同事务 currency.status draft→listed + currency_status_log 恰 1 行）；''rejected'' = 审核驳回（currency.status 仍 draft、不写 currency_status_log，但**本行必须落** ⇒ 驳回不得静默）。';
COMMENT ON COLUMN public.currency_review_log.memo IS
  '审核说明 / 原因（= 动作口请求体的 reason）。驳回路径必须携带非空 reason；通过路径可选。';
COMMENT ON COLUMN public.currency_review_log.actor_uid IS
  '审核人 uid（= admin）；**不得记成 owner**（§26.4 写死者）。token 侧取值，不得由客户端声明。';
COMMENT ON COLUMN public.currency_review_log.idempotency_key IS
  '审核动作的 ops: 幂等键，规范形 = ops:<admin_uid>:currency_review:<cid>（DL36 / DL93；键形 = 姊妹册 §23.3）。';
COMMENT ON COLUMN public.currency_review_log.request_fingerprint IS
  '请求指纹（DL96；由路由层按 business 字段集合服务端派生，具体拼接式 = 实现单现取）。';


-- ============================================================================
-- §B append-only 守卫（手法逐字照抄 0017:236-239 / 0023:112-127 / 0024 §B）
-- ============================================================================
CREATE OR REPLACE FUNCTION public.currency_review_log_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'currency_review_log is append-only: % forbidden (log_id=%)',
        TG_OP, COALESCE(OLD.log_id, 0);
END $$;

COMMENT ON FUNCTION public.currency_review_log_append_only() IS
  '批 8④：审核台账 append-only（BEFORE UPDATE OR DELETE 无条件 RAISE，原生 P0001，不借账本错误码 ⇒ 不建账本类对象）。只由迁移创建；体内无 DDL。诚实边界：不拦 TRUNCATE / DISABLE TRIGGER USER。';

DROP TRIGGER IF EXISTS trg_currency_review_log_append_only ON public.currency_review_log;
CREATE TRIGGER trg_currency_review_log_append_only
  BEFORE UPDATE OR DELETE ON public.currency_review_log
  FOR EACH ROW EXECUTE FUNCTION public.currency_review_log_append_only();


-- ============================================================================
-- §C 索引（逐条照 §26.7(d) · 0023:133-136 手法）
