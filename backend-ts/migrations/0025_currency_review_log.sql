  SELECT count(*) INTO v_n FROM pg_constraint WHERE conrelid = 'public.currency_review_log'::regclass AND contype = 'c' AND conname LIKE 'currency_review_log_%_ck';
  IF v_n <> 1 THEN RAISE EXCEPTION '0025 self-check FAILED: ledger CHECK count = % (expect 1)', v_n; END IF;
  -- `result` 闭集逐字 = {pending, approved, rejected}（渲染无关的归一化比对）
