-- PK 索引与 `currency_review_log_idem_uniq` 唯一索引由约束自带 ⇒ 连同下列 2 个具名索引共 4 个：
--   · `currency_review_log_cid_idx`       —— 按**单位**轴 + 时间检索（某单位的审核历史）；
