-- ============================================================================
-- §A 应用状态白名单（DL55）—— 唯一真源，供触发器与自检共用
-- ============================================================================
CREATE OR REPLACE FUNCTION public.job_application_status_transition_ok(p_from text, p_to text)
RETURNS boolean
LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p_from
    WHEN 'applied' THEN p_to IN ('accepted', 'rejected', 'withdrawn')
    ELSE false            -- accepted / rejected / withdrawn = 无出边（终态）
  END
$$;

COMMENT ON FUNCTION public.job_application_status_transition_ok(text, text) IS
  'DL55 应用状态白名单唯一真源：applied→{accepted,rejected,withdrawn}；accepted/rejected/withdrawn 无出边（终态）。';


-- ============================================================================
-- §B `public.job_application` 表（逐列照 §6.2 / DL54）
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.job_application (
  application_id bigint      GENERATED BY DEFAULT AS IDENTITY,
  job_id         bigint      NOT NULL,
  worker_uid     bigint      NOT NULL,
  status         text        NOT NULL DEFAULT 'applied',
  create_key     text        NOT NULL,
  time_created   timestamptz NOT NULL DEFAULT now(),
  time_updated   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT job_application_pk              PRIMARY KEY (application_id),
  -- DL75① / DL54：创建幂等键
  CONSTRAINT job_application_create_key_uniq UNIQUE (create_key),
  -- DL54：一人一单只有一条申请
  CONSTRAINT job_application_job_worker_uniq UNIQUE (job_id, worker_uid),
  -- DL54 / DL55 状态白名单（applied / withdrawn / rejected / accepted）
  CONSTRAINT job_application_status_enum     CHECK (status IN ('applied','withdrawn','rejected','accepted')),
  CONSTRAINT job_application_job_fk          FOREIGN KEY (job_id)     REFERENCES public.job(job_id),
  CONSTRAINT job_application_worker_fk       FOREIGN KEY (worker_uid) REFERENCES public.users(uid)
);

COMMENT ON TABLE public.job_application IS
  'P3 招工第二表（data-layer.spec v0.4 §6.2 / DL54）：报名。无分录动作（DL99）⇒ 无 ledger_event_keys 列；幂等靠 create_key 与 UNIQUE(job_id,worker_uid)。';

-- DL55：同一 job 最多一条 accepted（部分唯一索引；结构性保证并发「同时被选定」不可发生）
CREATE UNIQUE INDEX IF NOT EXISTS uniq_job_application_accepted
  ON public.job_application (job_id)
  WHERE status = 'accepted';

-- 索引（DL74 受控）：`(job_id, worker_uid)` 唯一约束自带索引已覆盖 job_id 前缀读
-- ⇒ 不另建 `(job_id)`；只补「我的报名」读口（worker_uid 轴）。
CREATE INDEX IF NOT EXISTS idx_job_application_worker
  ON public.job_application (worker_uid, time_created DESC);


