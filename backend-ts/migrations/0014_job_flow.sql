-- ============================================================================
-- §E apply-time 自检（DL48：不通过则整迁移回滚、不写版本行）
-- ============================================================================
DO $$
DECLARE
  v_missing  text;
  v_cols     int;
  v_idx      int;
  v_trg      int;
  v_def      text;
BEGIN
  -- ---------------------------------------------------------------- 结构断言
  IF to_regclass('public.job_application') IS NULL OR to_regclass('public.job_submission') IS NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: job_application / job_submission missing';
  END IF;

  SELECT count(*) INTO v_cols
    FROM information_schema.columns c
   WHERE c.table_schema = 'public' AND c.table_name = 'job_application';
  IF v_cols <> 7 THEN
    RAISE EXCEPTION '0014 self-check FAILED: public.job_application has % columns, expected 7 (DL54)', v_cols;
  END IF;

  SELECT string_agg(x.n, ',' ORDER BY x.n) INTO v_missing
    FROM (VALUES ('application_id'),('job_id'),('worker_uid'),('status'),
                 ('create_key'),('time_created'),('time_updated')) AS x(n)
   WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns c
                      WHERE c.table_schema='public' AND c.table_name='job_application' AND c.column_name = x.n);
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: job_application missing columns: %', v_missing;
  END IF;

  SELECT count(*) INTO v_cols
    FROM information_schema.columns c
   WHERE c.table_schema = 'public' AND c.table_name = 'job_submission';
  IF v_cols <> 10 THEN
    RAISE EXCEPTION '0014 self-check FAILED: public.job_submission has % columns, expected 10 (DL56)', v_cols;
  END IF;

  SELECT string_agg(x.n, ',' ORDER BY x.n) INTO v_missing
    FROM (VALUES ('submission_id'),('job_id'),('worker_uid'),('deliverable'),('review_status'),
                 ('reviewed_by'),('reviewed_at'),('review_memo'),('create_key'),('time_created')) AS x(n)
   WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns c
                      WHERE c.table_schema='public' AND c.table_name='job_submission' AND c.column_name = x.n);
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: job_submission missing columns: %', v_missing;
  END IF;

  -- DL99：无分录动作表**不得**有 ledger_event_keys（证明「未借账本幂等」）
  SELECT string_agg(x.n, ',' ORDER BY x.n) INTO v_missing
    FROM (VALUES ('ledger_event_keys')) AS x(n)
   WHERE EXISTS (SELECT 1 FROM information_schema.columns c
                  WHERE c.table_schema='public' AND c.column_name = x.n
                    AND c.table_name IN ('job_application','job_submission'));
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: DL99 violation, no-entry tables must not carry: %', v_missing;
  END IF;

  -- UNIQUE (job_id, worker_uid)（DL54）
  SELECT count(*) INTO v_idx
    FROM pg_constraint k
   WHERE k.conname = 'job_application_job_worker_uniq'
     AND k.contype = 'u'
     AND k.conrelid = 'public.job_application'::regclass;
  IF v_idx <> 1 THEN
    RAISE EXCEPTION '0014 self-check FAILED: UNIQUE(job_id,worker_uid) missing (DL54)';
  END IF;

  -- 部分唯一索引（DL55）：唯一 + `WHERE (status = 'accepted')`
  SELECT indexdef INTO v_def
    FROM pg_indexes i
   WHERE i.schemaname='public' AND i.tablename='job_application'
     AND i.indexname = 'uniq_job_application_accepted';
  IF v_def IS NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: partial unique index uniq_job_application_accepted missing (DL55)';
  END IF;
  IF position('CREATE UNIQUE INDEX' in upper(v_def)) = 0
     OR position('WHERE' in upper(v_def)) = 0
     OR position('accepted' in lower(v_def)) = 0 THEN
    RAISE EXCEPTION '0014 self-check FAILED: uniq_job_application_accepted is not a partial unique index: %', v_def;
  END IF;

  -- 触发器启用态（DL76/DL79/DL75③）：5 个 trg_（application 4 + submission 2 = 6，逐表断言）
  SELECT count(*) INTO v_trg
    FROM pg_trigger t
   WHERE NOT t.tgisinternal AND t.tgenabled = 'O'
     AND t.tgrelid = 'public.job_application'::regclass;
  IF v_trg <> 4 THEN
    RAISE EXCEPTION '0014 self-check FAILED: job_application enabled triggers = %, expected 4', v_trg;
  END IF;
  SELECT count(*) INTO v_trg
    FROM pg_trigger t
   WHERE NOT t.tgisinternal AND t.tgenabled = 'O'
     AND t.tgrelid = 'public.job_submission'::regclass;
  IF v_trg <> 2 THEN
    RAISE EXCEPTION '0014 self-check FAILED: job_submission enabled triggers = %, expected 2', v_trg;
  END IF;

  IF to_regprocedure('public.job_application_status_transition_ok(text,text)') IS NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: job_application_status_transition_ok(text,text) missing';
  END IF;

  -- 函数体内禁 DDL（DL142 同精神；本迁只有守卫函数）
  --   注：探测串用 chr(36) 拼 dollar-quote —— 本块自身是 dollar-quoted body，
  --   体内出现字面 dollar-quote 标记会提前闭合（同 0013 的实测）。
  SELECT string_agg(t.f || ':' || t.p, ',') INTO v_missing FROM (
    SELECT f.fn AS f, p.p AS p
      FROM (VALUES ('public.job_application_status_guard()'),
                   ('public.job_application_create_key_guard()'),
                   ('public.job_application_touch_time_updated()'),
                   ('public.job_application_no_delete()'),
                   ('public.job_submission_immutable_guard()'),
                   ('public.job_submission_no_delete()')) AS f(fn),
           (VALUES ('create table'),('alter table'),('drop table'),('truncate'),('create index'),
                   ('create function'),('rename to'),('do ' || chr(36) || chr(36))) AS p(p)
     WHERE position(upper(p.p) in upper(pg_get_functiondef(f.fn::regprocedure))) > 0
  ) AS t;
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION '0014 self-check FAILED: DDL token(s) inside function bodies: %', v_missing;
  END IF;

  -- ---------------------------------------------------------------- 纯函数断言（应用状态白名单，正全集）
  IF NOT public.job_application_status_transition_ok('applied','accepted')
     OR NOT public.job_application_status_transition_ok('applied','rejected')
     OR NOT public.job_application_status_transition_ok('applied','withdrawn') THEN
    RAISE EXCEPTION '0014 self-check FAILED: application whitelist missing an allowed transition (DL55)';
  END IF;
  IF public.job_application_status_transition_ok('applied','applied')
     OR public.job_application_status_transition_ok('accepted','applied')
     OR public.job_application_status_transition_ok('accepted','rejected')
     OR public.job_application_status_transition_ok('rejected','accepted')
     OR public.job_application_status_transition_ok('withdrawn','accepted') THEN
    RAISE EXCEPTION '0014 self-check FAILED: application whitelist admits a forbidden transition (DL55)';
  END IF;

  RAISE NOTICE '0014 self-check OK: job_application cols=7 trg=4 / job_submission cols=10 trg=2 / partial-unique(accepted) ok';
END $$;
