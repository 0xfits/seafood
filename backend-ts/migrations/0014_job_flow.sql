END $$;

COMMENT ON FUNCTION public.job_application_no_delete() IS
  'DL79：业务表禁物理删除（终结 = status 位）。触发器执行序按名字母序：create_key → status → time_updated。';

-- D5 job_submission 列级不可变守卫（DL56）
--   ① deliverable / job_id / worker_uid / create_key 永不可改；
--   ② review_status 只允许 pending → {approved, rejected}；
--   ③ 结论落定（review_status <> 'pending'）后 review_* 四列冻结；
--   ④ reviewed_by / reviewed_at / review_memo 各自一次写定（已非空/非 NULL 后不可改）。
CREATE OR REPLACE FUNCTION public.job_submission_immutable_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.job_id      IS DISTINCT FROM OLD.job_id
     OR NEW.worker_uid IS DISTINCT FROM OLD.worker_uid
     OR NEW.deliverable IS DISTINCT FROM OLD.deliverable
     OR NEW.create_key  IS DISTINCT FROM OLD.create_key THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job_submission.immutable', 'reason', 'job_submission_core_immutable',
                         'submission_id', OLD.submission_id::text));
  END IF;

  IF NEW.review_status IS DISTINCT FROM OLD.review_status THEN
    IF NOT (OLD.review_status = 'pending' AND NEW.review_status IN ('approved', 'rejected')) THEN
      PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
        jsonb_build_object('field', 'job_submission.review_status', 'reason', 'job_review_status_invalid',
                           'from', OLD.review_status, 'to', NEW.review_status,
                           'submission_id', OLD.submission_id::text));
    END IF;
  END IF;

  -- ③ 结论落定后 review_* 冻结
  IF OLD.review_status <> 'pending'
     AND (NEW.review_status IS DISTINCT FROM OLD.review_status
          OR NEW.reviewed_by  IS DISTINCT FROM OLD.reviewed_by
          OR NEW.reviewed_at  IS DISTINCT FROM OLD.reviewed_at
          OR NEW.review_memo  IS DISTINCT FROM OLD.review_memo) THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job_submission.review', 'reason', 'job_review_immutable',
                         'review_status', OLD.review_status, 'submission_id', OLD.submission_id::text));
  END IF;

  -- ④ 三列各自一次写定
  IF (OLD.reviewed_by IS NOT NULL AND NEW.reviewed_by IS DISTINCT FROM OLD.reviewed_by)
     OR (OLD.reviewed_at IS NOT NULL AND NEW.reviewed_at IS DISTINCT FROM OLD.reviewed_at)
     OR (OLD.review_memo <> '' AND NEW.review_memo IS DISTINCT FROM OLD.review_memo) THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job_submission.review_cols', 'reason', 'job_review_col_once_only',
                         'submission_id', OLD.submission_id::text));
  END IF;
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_submission_immutable_guard() IS
  'DL56：列级不可变守卫（deliverable/job_id/worker_uid/create_key 永不可改；review_* 只允许从 NULL/pending 一次写定，之后冻结）。护栏强度=行触发器；不拦 TRUNCATE / DISABLE TRIGGER USER。';

-- D6 job_submission 禁 DELETE（DL79）
CREATE OR REPLACE FUNCTION public.job_submission_no_delete() RETURNS trigger
