-- D1 job_application 状态转移白名单（DL55）
CREATE OR REPLACE FUNCTION public.job_application_status_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NOT public.job_application_status_transition_ok(OLD.status, NEW.status) THEN
      PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
        jsonb_build_object('field', 'job_application.status', 'reason', 'JOB_APPLICATION_STATE_INVALID',
                           'from', OLD.status, 'to', NEW.status,
                           'application_id', OLD.application_id::text));
    END IF;
  END IF;
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_application_status_guard() IS
  'DL55：应用状态白名单（唯一真源 = public.job_application_status_transition_ok）。违反 ⇒ 借码 LD011 LEDGER_CURRENCY_INVALID_TRANSITION（integrity ⇒ 409）+ reason=JOB_APPLICATION_STATE_INVALID。';

-- D2 job_application 创建键一次写定（DL75① 指纹一致 ⇒ 不可变）
CREATE OR REPLACE FUNCTION public.job_application_create_key_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.create_key IS DISTINCT FROM OLD.create_key THEN
    PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
      jsonb_build_object('field', 'job_application.create_key', 'reason', 'job_application_create_key_immutable',
                         'application_id', OLD.application_id::text));
  END IF;
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_application_create_key_guard() IS
  'DL75①：job_application.create_key 永不可改（幂等键指纹稳定）。';

-- D3 job_application time_updated 统一刷新（DL75③ / R5）
CREATE OR REPLACE FUNCTION public.job_application_touch_time_updated() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.time_updated := now();
  RETURN NEW;
END $$;

COMMENT ON FUNCTION public.job_application_touch_time_updated() IS
  'DL75③ / R5：job_application.time_updated 由 BEFORE UPDATE 触发器统一刷新，不接受客户端传时间。';

-- D4 job_application 禁 DELETE（DL79）
CREATE OR REPLACE FUNCTION public.job_application_no_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM public.ledger_raise('LEDGER_CURRENCY_INVALID_TRANSITION',
    jsonb_build_object('field', 'job_application', 'reason', 'job_application_delete_forbidden',
