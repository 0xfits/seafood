--   `CREATE UNIQUE INDEX IF NOT EXISTS` / `CREATE OR REPLACE FUNCTION` /
--   `DROP TRIGGER IF EXISTS` + `CREATE TRIGGER`；末尾 apply-time `DO` 自检
--   （结构 + 纯函数白名单正/负全集 + 触发器启用态 + 函数体内无 DDL）；
--   任一失败 ⇒ 整迁移回滚、不写版本行。
--
-- 诚实边界（不得夸大）
--   · 「列级不可变 / 一次写定 / 最多一条 accepted」都是**防应用层事故的护栏**：
--     `TRUNCATE` 不触发行触发器，超管 `ALTER TABLE ... DISABLE TRIGGER USER` 可旁路
