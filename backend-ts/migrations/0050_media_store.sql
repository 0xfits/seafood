-- ============================================================================
-- §① 表 public.media（7 列 + 去重键 · 逐列 = data-layer.spec §40.1 契约表）
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.media (
  media_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sha256 char(64) NOT NULL,
  content_type text NOT NULL CHECK (content_type IN ('image/webp','image/jpeg','image/png')),
  bytes bytea NOT NULL,
  size_bytes integer NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 2097152),
  owner_uid bigint NOT NULL REFERENCES public.users(uid),
  time_created timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT media_sha256_size_uniq UNIQUE (sha256, size_bytes)
);


-- ============================================================================
-- §② sha256 检索索引（B33 孤儿清理与内容排查按摘要取行；§40.3 实现单裁量项）
-- ============================================================================

CREATE INDEX IF NOT EXISTS media_sha256_idx ON public.media (sha256);


-- ============================================================================
-- §③ apply-time 自检（纯读 · 不写业务数据 · 不借账本错误码）
--     断言「表 / 7 列（类型 · NOT NULL · identity 语义）/ 约束（1 PK + 1 UNIQUE +
--     2 CHECK + 1 FK）/ 索引」全部在场，任一不成立 ⇒ RAISE ⇒ 整迁移回滚、不写版本行。
--     重跑免疫：IF NOT EXISTS 下读数恒同。
-- ============================================================================

DO $$
DECLARE
  v_matched int;
  v_text    text;
  v_count   int;
BEGIN
  -- ① 表在场
  IF to_regclass('public.media') IS NULL THEN
    RAISE EXCEPTION '0050 self-check failed: table public.media is missing';
  END IF;

  -- ② 逐列在场且类型 / NOT NULL 契约相符（format_type 口径 · 恰 7/7 命中）
  SELECT count(*) INTO v_matched
    FROM (VALUES
      ('media_id',     'bigint'),
      ('sha256',       'character(64)'),
      ('content_type', 'text'),
      ('bytes',        'bytea'),
      ('size_bytes',   'integer'),
      ('owner_uid',    'bigint'),
      ('time_created', 'timestamp with time zone')
    ) AS want(col, typ)
    JOIN pg_attribute AS a ON a.attrelid = 'public.media'::regclass AND a.attname = want.col
   WHERE a.attnum > 0
     AND NOT a.attisdropped
     AND a.attnotnull
     AND format_type(a.atttypid, a.atttypmod) = want.typ
     AND a.attrelid IN (SELECT oid FROM pg_class WHERE relnamespace = 'public'::regnamespace);
  IF v_matched IS DISTINCT FROM 7 THEN
    RAISE EXCEPTION '0050 self-check failed: column/type/notnull mismatch, matched %/7', v_matched;
  END IF;

  -- ③ media_id = GENERATED BY DEFAULT AS IDENTITY（attidentity = 'd'；'a' = ALWAYS 不符契约）
  SELECT a.attidentity::text INTO v_text
    FROM pg_attribute AS a
   WHERE a.attrelid = 'public.media'::regclass AND a.attname = 'media_id';
  IF v_text IS DISTINCT FROM 'd' THEN
    RAISE EXCEPTION '0050 self-check failed: media_id attidentity = % (expect d = BY DEFAULT)', v_text;
  END IF;

  -- ④ 恰 1 个主键
  SELECT count(*) INTO v_count
    FROM pg_constraint WHERE conrelid = 'public.media'::regclass AND contype = 'p';
  IF v_count IS DISTINCT FROM 1 THEN
    RAISE EXCEPTION '0050 self-check failed: primary keys = % (expect 1)', v_count;
  END IF;

  -- ⑤ 去重键 UNIQUE(sha256, size_bytes) 具名在场（内容寻址去重的承重墙）
  SELECT pg_get_constraintdef(oid) INTO v_text
    FROM pg_constraint
   WHERE conrelid = 'public.media'::regclass AND contype = 'u' AND conname = 'media_sha256_size_uniq';
  IF v_text IS NULL OR v_text NOT LIKE '%sha256%' OR v_text NOT LIKE '%size_bytes%' THEN
    RAISE EXCEPTION '0050 self-check failed: media_sha256_size_uniq missing or wrong shape (%)', COALESCE(v_text, '<null>');
  END IF;

  -- ⑥ content_type 三值闭集 CHECK 在场（三值逐字在场 ⇒ 第 4 值结构上不可入库）
  SELECT pg_get_constraintdef(oid) INTO v_text
    FROM pg_constraint
   WHERE conrelid = 'public.media'::regclass AND contype = 'c'
     AND pg_get_constraintdef(oid) LIKE '%content_type%';
  IF v_text IS NULL OR v_text NOT LIKE '%image/webp%' OR v_text NOT LIKE '%image/jpeg%' OR v_text NOT LIKE '%image/png%' THEN
    RAISE EXCEPTION '0050 self-check failed: content_type CHECK missing or wrong shape (%)', COALESCE(v_text, '<null>');
  END IF;

  -- ⑦ size_bytes ∈ (0, 2097152] CHECK 在场（与路由侧 ≤2MiB 闸同构）
  SELECT pg_get_constraintdef(oid) INTO v_text
    FROM pg_constraint
   WHERE conrelid = 'public.media'::regclass AND contype = 'c'
     AND pg_get_constraintdef(oid) LIKE '%size_bytes%';
  IF v_text IS NULL OR v_text NOT LIKE '%2097152%' THEN
    RAISE EXCEPTION '0050 self-check failed: size_bytes CHECK missing or wrong shape (%)', COALESCE(v_text, '<null>');
  END IF;

  -- ⑧ owner_uid → users(uid) 外键恰 1 条
  SELECT count(*) INTO v_count
    FROM pg_constraint
   WHERE conrelid = 'public.media'::regclass AND contype = 'f'
     AND confrelid = 'public.users'::regclass;
  IF v_count IS DISTINCT FROM 1 THEN
    RAISE EXCEPTION '0050 self-check failed: FK to public.users = % (expect 1)', v_count;
  END IF;

  -- ⑨ sha256 检索索引在场（首列 = sha256）
  SELECT count(*) INTO v_count
    FROM pg_index AS i
    JOIN pg_class AS ic ON ic.oid = i.indexrelid
   WHERE i.indrelid = 'public.media'::regclass AND ic.relname = 'media_sha256_idx'
     AND pg_get_indexdef(i.indexrelid) LIKE '%sha256%';
  IF v_count IS DISTINCT FROM 1 THEN
    RAISE EXCEPTION '0050 self-check failed: index media_sha256_idx missing or wrong shape';
  END IF;

  RAISE NOTICE '0050 self-check OK: public.media present (7 columns/media_id identity BY DEFAULT/UNIQUE(sha256,size_bytes)/content_type+size_bytes CHECK/FK users(uid)/media_sha256_idx)';
END $$;
