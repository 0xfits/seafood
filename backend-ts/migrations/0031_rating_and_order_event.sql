-- ============================================================================
-- §A `public.rating`（双向互评评分行 · append-only · 四要素必锚）
-- ============================================================================
-- 列 / 约束逐项溯源自 §32.5(c) 草案（先例锚逐字）：
--   · `rating_id`         bigint GENERATED BY DEFAULT AS IDENTITY (PK) ← `0017:140` / `0023:65`
--   · `rater_uid`         bigint NOT NULL（E1 发件人 · 取自 token）← `0023:66`（actor_uid）
--   · `ratee_uid`         bigint NOT NULL（E2 被评人 · 聚合轴）← `0023:67`（target_uid）
--   · `target_type`       text NOT NULL（E3 标的类型 · `job`|`listing`）← `0026:47`（单标的枚举手法）
--   · `target_id`         bigint NOT NULL（E3 标 id · **多态 ⇒ 不建单列 FK**）← `0001:65`（ref_id）/ `0015:164`
--   · `direction`         text NOT NULL（E4 方向 · 4 值闭集 `R-9-31`）← `0025:51-58`
--   · `stars`             numeric(5,4) NOT NULL（`rating_policy.storageDecimals = 4`）← `0001:59`
--   · `idempotency_key`   text NOT NULL ← `0023:77`
--   · `request_fingerprint` text NOT NULL ← `0023:76`
--   · `memo`              text NOT NULL DEFAULT '' ← `0001:69` / `0023:80`
--   · `time_created`      timestamptz NOT NULL DEFAULT now() ← `0023:81`（周期筛选轴 · UTC 自然日）
--   · `rating_pk` PRIMARY KEY (rating_id) ← `0023:82`
--   · `rating_rater_fk` / `rating_ratee_fk` FK → public.users(uid) ← `0023:83`
--   · `rating_stars_rng` CHECK (stars >= 0 AND stars <= 5)（值域 = 需求 §2.1.2「0-5 星」DB 兜底）← `0007:93`
--   · `rating_direction_target_ck`：`target_type='job'` ⇒ `direction ∈ {poster_to_worker,worker_to_poster}`；
--     `target_type='listing'` ⇒ `direction ∈ {vendor_to_customer,customer_to_vendor}`（由 `target_type`
--     决定允许子集 · `R-9-31`）← `0023:88`（语义域 CHECK 手法）
--   · `rating_once_uniq` UNIQUE (rater_uid, target_type, target_id)（同一人 / 同一标的 / 一侧恰一次）← `0001:28`
--   · `rating_idem_uniq` UNIQUE (idempotency_key) ← `0001:74`
--   · 索引 `idx_rating_ratee_time (ratee_uid, time_created DESC)`（聚合轴）+ `idx_rating_target
--     (target_type, target_id, time_created DESC)`（单标的轴）← `0023:133`
--   · append-only：`BEFORE UPDATE OR DELETE` 无条件 `RAISE`（原生 `P0001`）← `0017:236-239` / `0023:112-127`
CREATE TABLE IF NOT EXISTS public.rating (
  rating_id           bigint      GENERATED BY DEFAULT AS IDENTITY,
  rater_uid           bigint      NOT NULL,
  ratee_uid           bigint      NOT NULL,
  target_type         text        NOT NULL,
  target_id           bigint      NOT NULL,
  direction           text        NOT NULL,
  stars               numeric(5,4) NOT NULL,
  idempotency_key     text        NOT NULL,
  request_fingerprint text        NOT NULL,
  memo                text        NOT NULL DEFAULT '',
  time_created        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT rating_pk               PRIMARY KEY (rating_id),
  CONSTRAINT rating_rater_fk         FOREIGN KEY (rater_uid) REFERENCES public.users(uid),
  CONSTRAINT rating_ratee_fk         FOREIGN KEY (ratee_uid) REFERENCES public.users(uid),
  -- ★ 值域 = 需求 §2.1.2「0-5 星」的 DB 兜底（越界必 23514）
  CONSTRAINT rating_stars_rng        CHECK (stars >= 0 AND stars <= 5),
  -- ★ `R-9-31`：由 `target_type` 决定 `direction` 允许子集（每侧恰 2 值）—— 同时钉死 `target_type` 闭集。
  CONSTRAINT rating_direction_target_ck CHECK (
    (target_type = 'job'     AND direction IN ('poster_to_worker', 'worker_to_poster'))
    OR (target_type = 'listing' AND direction IN ('vendor_to_customer', 'customer_to_vendor'))),
  -- ★ 同一人、同一标的、一个方向一侧恰一次（承 `R-9-4`「各打一次」）
  CONSTRAINT rating_once_uniq        UNIQUE (rater_uid, target_type, target_id),
  CONSTRAINT rating_idem_uniq        UNIQUE (idempotency_key)
);

COMMENT ON TABLE public.rating IS
  'P9③（Kong；依据 data-layer.spec v0.23 §32.5(c) + R-9-31）：**双向互评评分行**（append-only）。四要素必锚 —— E1 `rater_uid`（token 取）· E2 `ratee_uid`（聚合轴）· E3 `(target_type,target_id)`（job|listing）· E4 `direction`（4 值闭集）；缺一即不可算单边评分。`stars numeric(5,4)`（storageDecimals=4，0–5）。`UNIQUE (rater_uid,target_type,target_id)` = 一侧恰一次；`UNIQUE (idempotency_key)` = 幂等兜底。**保留原始行 + 查询期聚合（禁预聚合分桶 · R-9-1）**。append-only（BEFORE UPDATE OR DELETE 无条件 RAISE，原生 P0001，不借账本码）。护栏不拦 TRUNCATE / DISABLE TRIGGER USER。';

CREATE INDEX IF NOT EXISTS idx_rating_ratee_time
  ON public.rating (ratee_uid, time_created DESC);
CREATE INDEX IF NOT EXISTS idx_rating_target
  ON public.rating (target_type, target_id, time_created DESC);


-- ============================================================================
-- §B `public.listing_order_event`（订单状态事件 · append-only · 时点真源）
-- ============================================================================
-- 列 / 约束逐项溯源自 §32.4(e) 草案（先例锚逐字）：
--   · `event_id`   bigint GENERATED BY DEFAULT AS IDENTITY (PK) ← `0017:140` / `0023:65`
--   · `order_id`   bigint NOT NULL ← `0024:50`
--   · `event_type` text NOT NULL（闭集 6 值 = 状态集）← `0025:47`（`result IN (…)`）
--   · `from_status`/`to_status` text（迁移前后状态；`created` 事件 `from_status = NULL`）← `0017:141-142`
--   · `actor_uid`  bigint NOT NULL（**取自 token**）← `0023:66` / `0024:49`
--   · `txid`       bigint（成功资金事件 = 回执；无资金 = NULL）← `0023:79` / `0024:57`
--   · `idempotency_key` text NOT NULL ← `0023:77`
--   · `request_fingerprint` text NOT NULL ← `0023:76`
--   · `ref_type`/`ref_id` text/bigint ← `0001:64-65`
--   · `memo`       text ← `0023:80`
--   · `time_created` timestamptz NOT NULL DEFAULT now()（**时点真源 · R-9-28**）← `0023:81`
--   · `listing_order_event_pk` PRIMARY KEY (event_id) ← `0023:82`
--   · `listing_order_event_order_fk` FK (order_id) → public.listing_order(order_id) ← `0024:63`
--   · `listing_order_event_actor_fk` FK (actor_uid) → public.users(uid) ← `0023:83`
--   · `listing_order_event_type_enum` CHECK (event_type IN (… 6 值 …)) ← `0025:51-58`
--   · `listing_order_event_idem_uniq` UNIQUE (idempotency_key) ← `0001:74`
--   · 索引 `idx_listing_order_event_order_time (order_id, time_created)` ← `0024:107` / `0023:133`
--   · append-only ← `0017:236-239` / `0023:112-127`
CREATE TABLE IF NOT EXISTS public.listing_order_event (
  event_id            bigint      GENERATED BY DEFAULT AS IDENTITY,
  order_id            bigint      NOT NULL,
  event_type          text        NOT NULL,
  from_status         text,
  to_status           text,
  actor_uid           bigint      NOT NULL,
  txid                bigint,
  idempotency_key     text        NOT NULL,
  request_fingerprint text        NOT NULL,
  ref_type            text,
  ref_id              bigint,
  memo                text,
  time_created        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT listing_order_event_pk             PRIMARY KEY (event_id),
  CONSTRAINT listing_order_event_order_fk       FOREIGN KEY (order_id)  REFERENCES public.listing_order(order_id),
  CONSTRAINT listing_order_event_actor_fk       FOREIGN KEY (actor_uid) REFERENCES public.users(uid),
  -- 闭集 = 订单状态集 6 值（created/paid/shipped/received/refunded/cancelled）
  CONSTRAINT listing_order_event_type_enum      CHECK (event_type IN ('created','paid','shipped','received','refunded','cancelled')),
  CONSTRAINT listing_order_event_idem_uniq      UNIQUE (idempotency_key)
);

COMMENT ON TABLE public.listing_order_event IS
  'P9③（Kong；依据 data-layer.spec v0.23 §32.4(e) + R-9-28/R-9-32）：**订单状态事件表**（append-only）。逐订单 × 逐状态转移一行；「下单 / 付款 / 发货 / 收货」四时点由事件行 `time_created` 承载（**时点真源 · R-9-28**；`listing_order` 仅 `time_created`/`time_updated` 无逐状态时点 ⇒ T3/T4 必须由本表承载）。`event_type` 闭集 = 6 值。append-only（BEFORE UPDATE OR DELETE 无条件 RAISE，原生 P0001，不借账本码）。护栏不拦 TRUNCATE / DISABLE TRIGGER USER。';

CREATE INDEX IF NOT EXISTS idx_listing_order_event_order_time
  ON public.listing_order_event (order_id, time_created);


