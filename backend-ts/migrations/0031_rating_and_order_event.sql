DECLARE
  v_names  text;
  v_n      int;
  v_trg    int;
  v_covers int;
BEGIN
  -- ---------------------------------------------------------------- 两表在场
  IF to_regclass('public.rating')             IS NULL THEN RAISE EXCEPTION '0031 self-check FAILED: public.rating missing'; END IF;
  IF to_regclass('public.listing_order_event') IS NULL THEN RAISE EXCEPTION '0031 self-check FAILED: public.listing_order_event missing'; END IF;

  -- ---------------------------------------------------------------- 逐表列名逐字
  SELECT string_agg(column_name, ',' ORDER BY ordinal_position) INTO v_names
    FROM information_schema.columns WHERE table_schema='public' AND table_name='rating';
