    FROM information_schema.columns WHERE table_schema='public' AND table_name='listing_order_event';
  IF v_names <> 'event_id,order_id,event_type,from_status,to_status,actor_uid,txid,idempotency_key,request_fingerprint,ref_type,ref_id,memo,time_created' THEN
    RAISE EXCEPTION '0031 self-check FAILED: listing_order_event columns = %', v_names; END IF;

