  IF v_n <> 1 THEN RAISE EXCEPTION '0031 self-check FAILED: rating PK count = %', v_n; END IF;
  SELECT count(*) INTO v_n FROM pg_constraint WHERE conrelid='public.rating'::regclass AND contype='f';
  IF v_n <> 2 THEN RAISE EXCEPTION '0031 self-check FAILED: rating FK count = % (expect 2: rater/ratee)', v_n; END IF;
