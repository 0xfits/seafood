-- ============================================================================
-- §B append-only 守卫（手法逐字照抄 0017:236-239 / 0023:112-127 / 0025:79-91）
-- ============================================================================
CREATE OR REPLACE FUNCTION public.listing_review_log_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'listing_review_log is append-only: % forbidden (log_id=%)',
        TG_OP, COALESCE(OLD.log_id, 0);
END $$;

COMMENT ON FUNCTION public.listing_review_log_append_only() IS
  '批 8⑤：商品审核台账 append-only（BEFORE UPDATE OR DELETE 无条件 RAISE，原生 P0001，不借账本错误码 ⇒ 不建账本类对象）。只由迁移创建；体内无 DDL。诚实边界：不拦 TRUNCATE / DISABLE TRIGGER USER。';

DROP TRIGGER IF EXISTS trg_listing_review_log_append_only ON public.listing_review_log;
CREATE TRIGGER trg_listing_review_log_append_only
  BEFORE UPDATE OR DELETE ON public.listing_review_log
  FOR EACH ROW EXECUTE FUNCTION public.listing_review_log_append_only();


-- ============================================================================
-- §C 索引（逐条照 §28.6(d) · 0023:133-136 / 0025:101-104 手法）
