  '批 8⑤（Kong；依据 data-layer.spec v0.17 §28.6 + route-layer.spec v2.10 §25）：商品（listing）**审核动作的旁路台账**（变体 Ⅱ）。列风格 / 约束命名 / 索引形态 / append-only 手法照抄 0023 的 admin_ops_audit_log 与 0025 的 currency_review_log。**只增不删**：BEFORE UPDATE OR DELETE 无条件 RAISE。actor_uid FK users(uid)、listing_id FK listing(listing_id)。**成功行（approved）与拒绝行（rejected）同表**（result 闭集 = {approved, rejected}）。商品下架 / 冻结无账务分录（DL59）⇒ txid 恒 NULL（对账显式豁免）。**零 ALTER 既有表**。诚实边界：append-only 触发器不拦 TRUNCATE / DISABLE TRIGGER USER（同 0017 / 0023 / 0025）。';

