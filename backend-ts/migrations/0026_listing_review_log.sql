-- ============================================================================
-- §A `public.listing_review_log`（商品审核台账 · append-only · 逐列照 §28.6(b)）
-- ============================================================================
-- 命名依据（§28.6(a)）：资源词 `listing`（`R-8-24` 逐字路径族名）+ 台账后缀 `_review_log`
--   （同族先例 = `public.currency_review_log`（`0025:42`）—— 同后缀、同「审核台账」定性）
--   ⇒ `listing_review_log`。与后台页命名空间 `adminListingReview`（§27.6(b)）词根一致。
-- 分工（§28.2(d)）：本表 = 「**审核动作**」留痕（`approved`/`rejected`）；
--   商品**状态迁移**走**既有已白名单边** `listed → delisted` / `listed → frozen`
--   （`0015:83-93` `public.listing_status_transition_ok`）—— **不新增状态值**（`R-8-23③`）。
CREATE TABLE IF NOT EXISTS public.listing_review_log (
  log_id              bigint      GENERATED BY DEFAULT AS IDENTITY,          -- 0023:65 / 0024:49 / 0017:140（身份证 PK 先例）
  listing_id          bigint      NOT NULL,                                   -- 0023:71 / 0017:141（资源键列；本轴 = 商品；同轴先例 = listing_order.listing_id 0015:155）
  actor_uid           bigint      NOT NULL,                                   -- 0023:66 / 0024:50 / 0017:144（动作人 uid；token 侧；不得由客户端声明）
  result              text        NOT NULL,                                   -- 0023:78 / 0024:56（结论位手法；值域 = 下方 CHECK）
  request_fingerprint text        NOT NULL,                                   -- 0023:76 / 0024:59（DL96；服务端派生）
  idempotency_key     text        NOT NULL,                                   -- 0023:77 / 0024:58（DL146② / DL36 的 `ops:` 系）
  txid                bigint,                                                 -- 0023:79 / 0024:57（账本回执 txid；**商品无分录 ⇒ 本轴恒 NULL**，见 DL59）
  memo                text,                                                   -- 0017:145 / 0023:80 / 0024:60（驳回 = reason；可空）
  time_created        timestamptz NOT NULL DEFAULT now(),                     -- 0023:81 / 0024:61 / 0017:146（DB 生成，不得客户端传）
  CONSTRAINT listing_review_log_pk         PRIMARY KEY (log_id),                                              -- 0023:82 / 0024:62
  CONSTRAINT listing_review_log_actor_fk   FOREIGN KEY (actor_uid)  REFERENCES public.users(uid),             -- 0023:83 / 0024:63
  CONSTRAINT listing_review_log_listing_fk FOREIGN KEY (listing_id) REFERENCES public.listing(listing_id),    -- 0015:177（listing_order_listing_fk 同轴照抄）
  CONSTRAINT listing_review_log_result_ck  CHECK (result IN ('approved', 'rejected')),                        -- 0023:89（result 闭集手法）；值域 = R-8-23②（逐字取 0025:54 两值）
  -- ★ 沿用 `0023` 裁定四（「幂等键的语义约束**效果**、不约束**尝试**」）：
  --   同键同 `result` 重投 ⇒ `(key, result)` 冲突 ⇒ `DO NOTHING`（幂等重放，拒绝行不放大）；
  --   同键异 `result`（先驳后成 / 先成后驳）⇒ 允许，各留一行（§25.3）。
  CONSTRAINT listing_review_log_idem_uniq  UNIQUE (idempotency_key, result)                                   -- 0023:99 / 0024:72
);

