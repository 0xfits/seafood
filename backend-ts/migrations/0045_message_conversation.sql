-- ============================================================================
-- 0045_message_conversation.sql · A5 收口（站内信最小闭环）· data-layer.spec v0.32 §38
--   conversation（受限可变面）+ message（append-only）两表全量 DDL
--   + 5 函数 5 触发器（3 会话闸 + 2 消息闸）+ 4 索引 + 5 FK
-- ============================================================================
-- 内容契约（冻结于 docs/data-layer.spec.md v0.32 §38.2 / §38.3 / §38.5 / §38.8）：
--   · conversation：per-listing 会话，UNIQUE(listing_id, buyer_uid)（Z1）；
--     删除禁止（DELETE / TRUNCATE 双闸），更新仅限 3 列
--     （buyer_last_read_msg_id / seller_last_read_msg_id / time_updated）且两读水位单调不减
--     （read_mark_only 闸，A5-DL-G3）。
--   · message：append-only（UPDATE / DELETE / TRUNCATE 三闸齐，A5-DL-G5）；
--     body 域 [1, 2000] 字符（A5-DL-N2，char_length 按 PG 字符语义）；
--     msg_id = IDENTITY 全局单调（A5-DL-N3），会话内 keyset 游标直接用它（DL25 体例，禁 OFFSET）。
--   · seller_uid = listing.seller_uid 的派生冗余：唯一写法 = 单语句 INSERT … SELECT 从
--     listing 取值（A5-DL-G1，写路径保证，无跨表 CHECK）。
--   · 无已读回执 / 无撤回 / 无编辑 / 无图片列（Z9「不做」清单 ⇒ 不建对应列，不留占位列）。
--   · 频次上限无计数器表、无计数触发器：计数 = 查询期派生（§38.6 / §38.7，append-only 纯度）。
--   · create_key 语义 = A5-DL-G4：会话幂等承重墙 = UNIQUE(listing_id, buyer_uid) 自然键 +
--     ON CONFLICT 取既有行；create_key 落确定性派生值 open:<listing_id>:<buyer_uid>（服务端派生），
--     承 R51/R52 指纹口径（同键重投 = 幂等重放、改内容 = 响亮拒绝）。
--
-- 手法（0043 体例）：
--   · 守卫函数命名沿 `<table>_no_*` 家族（禁复用既有 `_append_only` 函数名 ——
--     CREATE OR REPLACE 会覆写既有函数体 ⇒ 硬禁）。
--   · 错误 = 原生 RAISE EXCEPTION（SQLSTATE P0001，不借账本错误码）。
--   · TRUNCATE 闸必须 FOR EACH STATEMENT（0043 教训：行级闸不拦 TRUNCATE）。
--
-- 硬禁（§38.8 内容闭集之外一律不做）：
--   · 不改任何既有对象 / 不 CREATE OR REPLACE 既有函数体 / 不写业务数据 / 不借账本错误码。
--   · 0001–0044 一字不动（checksum 冻结，migrate.ts 整链 ABORT 红线沿用）。
--   · 幂等：CREATE TABLE IF NOT EXISTS + CREATE INDEX IF NOT EXISTS +
--     CREATE OR REPLACE FUNCTION（新建函数）+ DROP TRIGGER IF EXISTS + CREATE TRIGGER +
--     末尾 apply-time DO 自检（纯目录只读）；任一失败 ⇒ 整迁移回滚、不写版本行。
-- ============================================================================


-- ============================================================================
-- §① 表一 public.conversation（受限可变面 · §38.2 全量）
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.conversation (
  conversation_id         bigint      GENERATED BY DEFAULT AS IDENTITY,
  listing_id              bigint      NOT NULL,
  buyer_uid               bigint      NOT NULL,
  seller_uid              bigint      NOT NULL,              -- 冗余列（A5-DL-G1：单语句 INSERT…SELECT 派生）
  buyer_last_read_msg_id  bigint      NOT NULL DEFAULT 0,    -- 买方已读水位（单调不减，A5-DL-N1 初值 0）
  seller_last_read_msg_id bigint      NOT NULL DEFAULT 0,    -- 卖方已读水位（单调不减，A5-DL-N1 初值 0）
  create_key              text        NOT NULL,              -- R51/R52 指纹口径（A5-DL-G4）
  time_created            timestamptz NOT NULL DEFAULT now(),
  time_updated            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversation_pk                   PRIMARY KEY (conversation_id),
  CONSTRAINT conversation_listing_fk           FOREIGN KEY (listing_id) REFERENCES public.listing(listing_id),
  CONSTRAINT conversation_buyer_fk             FOREIGN KEY (buyer_uid)  REFERENCES public.users(uid),
  CONSTRAINT conversation_seller_fk            FOREIGN KEY (seller_uid) REFERENCES public.users(uid),
  CONSTRAINT conversation_parties_distinct     CHECK (buyer_uid <> seller_uid),
  CONSTRAINT conversation_create_key_uniq      UNIQUE (create_key),
  CONSTRAINT conversation_buyer_listing_uniq   UNIQUE (listing_id, buyer_uid)
);

-- 读路径索引（keyset 游标 = (time_updated DESC, conversation_id DESC)，DL25 体例；禁 OFFSET）
CREATE INDEX IF NOT EXISTS idx_conversation_buyer  ON public.conversation (buyer_uid,  time_updated DESC, conversation_id DESC);
CREATE INDEX IF NOT EXISTS idx_conversation_seller ON public.conversation (seller_uid, time_updated DESC, conversation_id DESC);


-- ============================================================================
-- §② 表二 public.message（append-only · §38.3 全量）
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.message (
  msg_id           bigint      GENERATED BY DEFAULT AS IDENTITY,
  conversation_id  bigint      NOT NULL,
  from_uid         bigint      NOT NULL,
  body             text        NOT NULL,
  time_created     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT message_pk              PRIMARY KEY (msg_id),
  CONSTRAINT message_conversation_fk FOREIGN KEY (conversation_id) REFERENCES public.conversation(conversation_id),
  CONSTRAINT message_from_fk         FOREIGN KEY (from_uid)        REFERENCES public.users(uid),
  CONSTRAINT message_body_len        CHECK (char_length(body) BETWEEN 1 AND 2000)
);

-- keyset 游标 = msg_id（DL25 体例）；(conversation_id) 前导列同时服务 FK。
CREATE INDEX IF NOT EXISTS idx_message_conversation ON public.message (conversation_id, msg_id DESC);
-- 全局日频次计数（§38.7 R2）取数索引。
CREATE INDEX IF NOT EXISTS idx_message_from_day     ON public.message (from_uid, time_created);


-- ============================================================================
-- §③ 会话三闸（§38.5 · conversation 不入 append-only 家族 = 受限可变面）
-- ============================================================================

-- ③-a 删除闸：会话是双方法律往来留痕，删行会造 message.conversation_id 孤儿 ⇒ DELETE 裁死。
CREATE OR REPLACE FUNCTION public.conversation_no_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'conversation is not deletable';
END $$;

DROP TRIGGER IF EXISTS trg_conversation_no_delete ON public.conversation;
CREATE TRIGGER trg_conversation_no_delete
  BEFORE DELETE ON public.conversation FOR EACH ROW EXECUTE FUNCTION public.conversation_no_delete();

-- ③-b 受限更新闸：仅 3 列可变（两读水位 + time_updated），且两读水位单调不减。
--      逐列比较 OLD / NEW：凡不在允许集内的列发生变化 ⇒ RAISE；
--      NEW.buyer_last_read_msg_id >= OLD.buyer_last_read_msg_id、
--      NEW.seller_last_read_msg_id >= OLD.seller_last_read_msg_id（防「重置已读」刷未读）。
--      time_updated 只由消息追加写路径推进；读标记单独推进时保持原值。
CREATE OR REPLACE FUNCTION public.conversation_read_mark_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.conversation_id    IS DISTINCT FROM OLD.conversation_id
    OR NEW.listing_id       IS DISTINCT FROM OLD.listing_id
    OR NEW.buyer_uid        IS DISTINCT FROM OLD.buyer_uid
    OR NEW.seller_uid       IS DISTINCT FROM OLD.seller_uid
    OR NEW.create_key       IS DISTINCT FROM OLD.create_key
    OR NEW.time_created     IS DISTINCT FROM OLD.time_created
  THEN
    RAISE EXCEPTION 'conversation update is restricted to read watermarks and time_updated';
  END IF;

  IF NEW.buyer_last_read_msg_id < OLD.buyer_last_read_msg_id
    OR NEW.seller_last_read_msg_id < OLD.seller_last_read_msg_id
  THEN
    RAISE EXCEPTION 'conversation read watermark is monotonic and cannot decrease';
  END IF;

  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_conversation_read_mark_only ON public.conversation;
CREATE TRIGGER trg_conversation_read_mark_only
  BEFORE UPDATE ON public.conversation FOR EACH ROW EXECUTE FUNCTION public.conversation_read_mark_only();

-- ③-c TRUNCATE 闸（语句级 —— 行级闸不拦 TRUNCATE，0043 教训）。
CREATE OR REPLACE FUNCTION public.conversation_no_truncate() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'conversation truncate is forbidden';
END $$;

DROP TRIGGER IF EXISTS trg_conversation_no_truncate ON public.conversation;
CREATE TRIGGER trg_conversation_no_truncate
  BEFORE TRUNCATE ON public.conversation FOR EACH STATEMENT EXECUTE FUNCTION public.conversation_no_truncate();


-- ============================================================================
-- §④ 消息两闸（append-only 全集 · A5-DL-G5）
-- ============================================================================

-- ④-a UPDATE / DELETE 行级闸（BEFORE UPDATE OR DELETE，tgtype 27 形态，0043 §35.2 同法）。
CREATE OR REPLACE FUNCTION public.message_no_update_or_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'message is append-only';
END $$;

DROP TRIGGER IF EXISTS trg_message_no_update_or_delete ON public.message;
CREATE TRIGGER trg_message_no_update_or_delete
  BEFORE UPDATE OR DELETE ON public.message FOR EACH ROW EXECUTE FUNCTION public.message_no_update_or_delete();

-- ④-b TRUNCATE 语句级闸。
CREATE OR REPLACE FUNCTION public.message_no_truncate() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'message truncate is forbidden';
END $$;

DROP TRIGGER IF EXISTS trg_message_no_truncate ON public.message;
CREATE TRIGGER trg_message_no_truncate
  BEFORE TRUNCATE ON public.message FOR EACH STATEMENT EXECUTE FUNCTION public.message_no_truncate();


-- ============================================================================
-- §⑤ apply-time 自检（纯目录只读 · 不 INSERT / 不 UPDATE / 不借账本错误码）
--     逐项断言「DDL 全在场」；任一缺席 ⇒ RAISE ⇒ 整迁移回滚、不写版本行。
-- ============================================================================

DO $$
DECLARE
  missing text;
BEGIN
  -- ⑤-a 两表在场
  SELECT string_agg(v.tbl, ',') INTO missing FROM (
    VALUES ('conversation'), ('message')
  ) AS v(tbl)  -- 表名清单（§38.2 / §38.3）
  WHERE NOT EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = v.tbl AND table_type = 'BASE TABLE'
  );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'apply self-check failed: missing table(s): %', missing;
  END IF;

  -- ⑤-b 5 触发器在场且启用
  SELECT string_agg(v.trg, ',') INTO missing FROM (
    VALUES ('trg_conversation_no_delete'),
           ('trg_conversation_read_mark_only'),
           ('trg_conversation_no_truncate'),
           ('trg_message_no_update_or_delete'),
           ('trg_message_no_truncate')
  ) AS v(trg)
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_trigger trg
    JOIN pg_class cls ON cls.oid = trg.tgrelid
    JOIN pg_namespace nsp ON nsp.oid = cls.relnamespace
    WHERE nsp.nspname = 'public' AND trg.tgname = v.trg
      AND NOT trg.tgisinternal AND trg.tgenabled IN ('O', 'A')
  );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'apply self-check failed: missing trigger(s): %', missing;
  END IF;

  -- ⑤-c 5 函数在场
  SELECT string_agg(v.fn, ',') INTO missing FROM (
    VALUES ('conversation_no_delete'),
           ('conversation_read_mark_only'),
           ('conversation_no_truncate'),
           ('message_no_update_or_delete'),
           ('message_no_truncate')
  ) AS v(fn)
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.proname = v.fn
  );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'apply self-check failed: missing function(s): %', missing;
  END IF;

  -- ⑤-d 4 索引在场
  SELECT string_agg(v.idx, ',') INTO missing FROM (
    VALUES ('idx_conversation_buyer'),
           ('idx_conversation_seller'),
           ('idx_message_conversation'),
           ('idx_message_from_day')
  ) AS v(idx)
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE schemaname = 'public' AND indexname = v.idx
  );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'apply self-check failed: missing index(es): %', missing;
  END IF;

  -- ⑤-e 5 FK 在场（conversation 3 + message 2）
  SELECT string_agg(v.conname, ',') INTO missing FROM (
    VALUES ('conversation_listing_fk'),
           ('conversation_buyer_fk'),
           ('conversation_seller_fk'),
           ('message_conversation_fk'),
           ('message_from_fk')
  ) AS v(conname)
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class cls ON cls.oid = con.conrelid
    JOIN pg_namespace nsp ON nsp.oid = cls.relnamespace
    WHERE nsp.nspname = 'public' AND con.conname = v.conname AND con.contype = 'f'
  );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'apply self-check failed: missing foreign key(s): %', missing;
  END IF;

  -- ⑤-f 关键约束在场（PK / UNIQUE / CHECK 闭集）
  SELECT string_agg(v.conname, ',') INTO missing FROM (
    VALUES ('conversation_pk'), ('conversation_parties_distinct'),
           ('conversation_create_key_uniq'), ('conversation_buyer_listing_uniq'),
           ('message_pk'), ('message_body_len')
  ) AS v(conname)
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class cls ON cls.oid = con.conrelid
    JOIN pg_namespace nsp ON nsp.oid = cls.relnamespace
    WHERE nsp.nspname = 'public' AND con.conname = v.conname
  );
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'apply self-check failed: missing constraint(s): %', missing;
  END IF;
END $$;
